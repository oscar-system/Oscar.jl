@doc raw"""
    linear_quotient(G::MatGroup) -> LinearQuotient

Return the linear quotient by `G`, that is, the orbit space of the action of `G`
on the vector space of dimension `degree(G)`.

If the given group is not finite, an error is raised.

!!! danger "Implicit choice of representation"
    Let $V = K^n$ be the natural representation of the matrix group $G$.
    Then the object returned by `linear_quotient(G)` works with the dual
    representation, that is, the linear quotient is $V^\ast/G$.
    This is following a general convention in invariant theory in OSCAR.

# Examples
```jldoctest
julia> K, a = cyclotomic_field(4, :a);

julia> r = K[-1 0; 0 1]; s = K[a 0; 0 inv(a)];

julia> G = matrix_group(r, s);

julia> L = linear_quotient(G)
Linear quotient
  by matrix group of degree 2 over K
```
"""
function linear_quotient(G::MatGroup)
  @req is_finite(G) "The group must be finite"
  return LinearQuotient(G)
end

function Base.show(io::IO, ::MIME"text/plain", L::LinearQuotient)
  io = pretty(io)
  println(io, "Linear quotient")
  print(io, Indent(), "by ", Lowercase(), group(L), Dedent())
end

function Base.show(io::IO, L::LinearQuotient)
  if is_terse(io)
    print(io, "Linear quotient")
  else
    io = pretty(io)
    print(io, "Linear quotient by ")
    print(terse(io), Lowercase(), group(L))
  end
end

group(L::LinearQuotient) = L.group
base_ring(L::LinearQuotient) = base_ring(group(L))
base_ring_type(::Type{LinearQuotient{S,T}}) where {S,T} = base_ring_type(MatGroup{S,T})

