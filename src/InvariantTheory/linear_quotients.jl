function fixed_root_of_unity(L::LinearQuotient)
  if isdefined(L, :root_of_unity)
    return L.root_of_unity
  end

  e = exponent(Int, group(L))
  K = base_ring(L)

  if e == 1
    L.root_of_unity = (K(1), e)
  elseif e == 2
    L.root_of_unity = (K(-1), e)
  else
    x, f = Hecke.torsion_units_gen_order(K)
    fl, q = divides(f, e)
    fl || error("$(base_ring(L)) does not contain a $(e)-th root of unity")

    L.root_of_unity = (x^q, e)
  end
  return L.root_of_unity
end

# Somehow one needs to look up powers of a given root of unity quite often...
# Assumes that zeta is a primitive l-th root of unity
function _powers_of_root_of_unity(zeta::FieldElem, l::Int)
  K = parent(zeta)
  powers_of_zeta = Dict{elem_type(K),Int}()
  t = one(K)
  for i in 0:(l - 1)
    powers_of_zeta[t] = i
    t *= zeta
  end
  @assert is_one(t) "Given element is not a $l-th root of unity"

  return powers_of_zeta
end

