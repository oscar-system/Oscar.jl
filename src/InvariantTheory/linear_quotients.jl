@doc raw"""
    class_group(L::LinearQuotient) -> FinGenAbGroup, Map

Return the class group of the linear quotient `L` and a map from `group(L)` to
this group.

If `G = group(L)`, then the class group is `Ab(G/H)`, where `H` is the subgroup
of `G` generated by the pseudo-reflections, see [Ben93](@cite).

# Examples
```jldoctest
julia> K, a = cyclotomic_field(4, :a);

julia> r = K[-1 0; 0 1]; s = K[a 0; 0 inv(a)];

julia> G = matrix_group(r, s);

julia> L = linear_quotient(G);

julia> A, GtoA = class_group(L)
(Z/2, Map: G -> pc group -> A)
```
"""
function class_group(L::LinearQuotient)
  if isdefined(L, :class_group)
    return L.class_group
  end

  G = group(L)
  H, _ = _subgroup_of_pseudo_reflections(L)
  if !is_trivial(H)
    K, GtoK = quo(G, H)
  else
    K = G
  end
  A, KtoA = maximal_abelian_quotient(FinGenAbGroup, K)
  snfA, snfAtoA = snf(A)
  A = snfA
  KtoA = compose(KtoA, inv(snfAtoA))
  if !is_trivial(H)
    GtoA = compose(GtoK, KtoA)
  else
    GtoA = KtoA
  end
  L.class_group = A, GtoA
  return L.class_group
end

@doc raw"""
    is_pseudo_reflection(g::MatGroupElem)

Return `true` if `g` is a pseudo-reflection, `false` otherwise.

By a pseudo-reflection, we mean a matrix with fixed space of codimension 1.
"""
function is_pseudo_reflection(g::MatGroupElem)
  return rank(matrix(g) - matrix(one(parent(g)))) == 1
end

@doc raw"""
    subgroup_of_pseudo_reflections(G::MatGroup)

Return the subgroup `H` of `G` generated by the pseudo-reflections in `G` and an
embedding `H \to G`.

See also [`is_pseudo_reflection`](@ref).
"""
function subgroup_of_pseudo_reflections(G::MatGroup)
  g = elem_type(G)[]
  for c in conjugacy_classes(G)
    repc = representative(c)
    is_pseudo_reflection(repc) && push!(g, repc)
  end
  H, _ = sub(G, g; check=false)
  # H is only the subgroup generated by representatives of the conjugacy
  # classes, so we have to take the normal closure
  return normal_closure(G, H)
end

function _subgroup_of_pseudo_reflections(L::LinearQuotient)
  if isdefined(L, :reflection_subgroup)
    return L.reflection_subgroup
  end
  L.reflection_subgroup = subgroup_of_pseudo_reflections(group(L))
  return L.reflection_subgroup
end

