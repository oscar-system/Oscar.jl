mutable struct PrimaryInvarsCache{T}
  invars::Vector{T} # primary invariants
  ideal::MPolyIdeal{T} # ideal generated by the primary invariants

  function PrimaryInvarsCache{T}() where {T<:MPolyRingElem}
    z = new{T}()
    z.invars = T[]
    return z
  end
end

mutable struct SecondaryInvarsCache{T}
  invars::Vector{T} # secondary invariants
  is_irreducible::BitVector # is_irreducible[i] == true iff invars[i] is irreducible
  sec_in_irred::Vector{Vector{Int}}
  # sec_in_irred[i] gives the "exponent vector" for invars[i] in the irreducible
  # secondary invariants (hence length(sec_in_irred[i]) is equal to the number of
  # irreducible secondary invariants and not to length(invars))

  function SecondaryInvarsCache{T}() where {T<:MPolyRingElem}
    z = new{T}()
    z.invars = T[]
    z.is_irreducible = BitVector()
    z.sec_in_irred = Vector{Vector{Int}}()
    return z
  end
end

mutable struct FundamentalInvarsCache{PolyRingElemT,PolyRingT}
  invars::Vector{PolyRingElemT} # fundamental invariants

  # Graded polynomial ring in length(invars) variables such that
  # deg(gen(S, i)) == deg(invars[i])
  S::PolyRingT

  # Remember whether the fundamental invariants were computed from the primary
  # and secondary ones
  via_primary_and_secondary::Bool

  # For a primary or irreducible secondary invariant f, toS[f] gives the
  # representation of f as a polynomial in the fundamental invariants.
  # This field is only set, if via_primary_and_secondary is true.
  toS::Dict{PolyRingElemT,PolyRingElemT}

  function FundamentalInvarsCache{
    PolyRingElemT,PolyRingT
  }() where {PolyRingElemT<:MPolyRingElem,PolyRingT<:MPolyRing}
    z = new{PolyRingElemT,PolyRingT}()
    z.invars = PolyRingElemT[]
    return z
  end
end

mutable struct FinGroupInvarRing{FldT,GrpT,PolyRingElemT,PolyRingT,ActionT}
  field::FldT
  poly_ring::PolyRingT

  # The underlying polynomial ring needs to be created with
  # internal_ordering = :degrevlex for the application of divrem in the secondary
  # and fundamental invariants.
  # If the user gave us a polynomial ring (which is stored in poly_ring), this
  # might not be the case.
  poly_ring_internal::PolyRingT

  group::GrpT
  action::Vector{ActionT}

  modular::Bool

  primary::PrimaryInvarsCache{PolyRingElemT}
  secondary::SecondaryInvarsCache{PolyRingElemT}
  fundamental::FundamentalInvarsCache{PolyRingElemT,PolyRingT}

  presentation::MPolyAnyMap{MPolyQuoRing{PolyRingElemT},PolyRingT,Nothing,PolyRingElemT}

  reynolds_operator::MapFromFunc{PolyRingT,PolyRingT}

  molien_series::Generic.FracFieldElem{QQPolyRingElem}

  function FinGroupInvarRing(
    K::FldT, G::GrpT, action::Vector{ActionT}
  ) where {FldT<:Field,GrpT<:Group,ActionT}
    n = degree(G)
    # We want to use divrem w.r.t. degrevlex for the computation of secondary
    # invariants and fundamental invariants
    R, = graded_polynomial_ring(K, :x => 1:n; cached=false, internal_ordering=:degrevlex)
    return FinGroupInvarRing(K, G, action, R)
  end

  function FinGroupInvarRing(
    K::FldT, G::GrpT, action::Vector{ActionT}, poly_ring::PolyRingT
  ) where {FldT<:Field,GrpT<:Group,ActionT,PolyRingT<:MPolyDecRing}
    @assert coefficient_ring(poly_ring) === K
    @assert ngens(poly_ring) == degree(G)

    PolyRingElemT = elem_type(poly_ring)
    z = new{FldT,GrpT,PolyRingElemT,PolyRingT,ActionT}()
    z.field = K
    z.poly_ring = poly_ring
    z.group = G
    z.action = action
    z.modular = true
    if iszero(characteristic(K))
      z.modular = false
    else
      if !iszero(mod(order(G), characteristic(K)))
        z.modular = false
      end
    end

    # We want to use divrem w.r.t. degrevlex for the computation of secondary
    # invariants and fundamental invariants
    if internal_ordering(poly_ring) != :degrevlex
      z.poly_ring_internal, _ = graded_polynomial_ring(
        K, ngens(poly_ring); cached=false, internal_ordering=:degrevlex
      )
    end

    return z
  end
end

# Produces all monomials in R of degree d
struct AllMonomials{PolyRingT}
  R::PolyRingT
  d::Int # the degree
  weak_comp_iter::WeakCompositions{Int}

  on_all_vars::Bool # whether we work on all variables or a subset
  n_vars::Int # the number of variables we work on
  used_vars::Vector{Int} # indices of the variables we work on
  tmp::Vector{Int} # of length ngens(R), should be put back to zero after use

  function AllMonomials{PolyRingT}(R::PolyRingT, d::Int) where {PolyRingT}
    @assert d >= 0
    return new{PolyRingT}(
      R, d, weak_compositions(d, ngens(R); inplace=true), true, ngens(R)
    )
  end

  function AllMonomials{PolyRingT}(
    R::PolyRingT, d::Int, vars::Vector{Int}
  ) where {PolyRingT}
    @assert d >= 0
    vars = sort!(unique(vars))
    @assert minimum(vars; init=1) >= 1
    @assert maximum(vars; init=1) <= nvars(R)
    n_vars = length(vars)
    if n_vars == ngens(R)
      return AllMonomials{PolyRingT}(R, d)
    end

    tmp = zeros(Int, ngens(R))
    return new{PolyRingT}(
      R, d, weak_compositions(d, n_vars; inplace=true), false, n_vars, vars, tmp
    )
  end
end

