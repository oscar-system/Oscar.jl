abstract type VectorSpaceIterator{FieldT,IteratorT,ElemT} end

# This takes a basis of a vector space as an iterator and then "iterates" the
# space in three "phases":
# 1) iterate the basis using basis_iterator, so return one basis element at
#    a time
# 2) iterate all possible sums of basis elements
# 3) return random linear combinations of the basis elements (with integer
#    coefficients bounded by rand_bound)
#
# We collect the basis while iterating it, so that multiple iteration over the
# same VectorSpaceIterator do not need to recompute it. basis_iterator_state
# must always be a state of basis_iterator, so that
# iterate(basis_iterator, basis_iterator_state) returns the next element in the
# basis coming after basis_collected[end].
mutable struct VectorSpaceIteratorRand{FieldT,IteratorT,ElemT} <:
               VectorSpaceIterator{FieldT,IteratorT,ElemT}
  field::FieldT
  basis_iterator::IteratorT
  basis_collected::Vector{ElemT}
  basis_iterator_state::Any # I don't know the type of this and I don't think there
  # is a "type-stable" way of finding it out
  rand_bound::Int

  function VectorSpaceIteratorRand(
    K::FieldT, basis_iterator::IteratorT, bound::Int=10^5
  ) where {FieldT,IteratorT}
    VSI = new{FieldT,IteratorT,eltype(basis_iterator)}()
    VSI.field = K
    VSI.basis_iterator = basis_iterator
    VSI.basis_collected = eltype(basis_iterator)[]
    VSI.rand_bound = bound
    return VSI
  end
end

# The same things as for VectorSpaceIteratorRand apply besides that in "phase 3"
# all elements of the vector space are iterated in deterministic order (it is
# supposed to be finite after all).
mutable struct VectorSpaceIteratorFiniteField{FieldT,IteratorT,ElemT} <:
               VectorSpaceIterator{FieldT,IteratorT,ElemT}
  field::FieldT
  basis_iterator::IteratorT
  basis_collected::Vector{ElemT}
  basis_iterator_state::Any # I don't know the type of this and I don't think there
  # is a "type-stable" way of finding it out

  function VectorSpaceIteratorFiniteField(
    K::FieldT, basis_iterator::IteratorT
  ) where {
    FieldT<:Union{fpField,FpField,fqPolyRepField,FqPolyRepField,FqField},IteratorT
  }
    VSI = new{FieldT,IteratorT,eltype(basis_iterator)}()
    VSI.field = K
    VSI.basis_iterator = basis_iterator
    VSI.basis_collected = eltype(basis_iterator)[]
    return VSI
  end
end

struct MSetPartitions{T}
  M::MSet{T}
  num_to_key::Vector{T}
  key_to_num::Dict{T,Int}

  function MSetPartitions(M::MSet{T}) where {T}
    num_to_key = collect(keys(M.dict))
    key_to_num = Dict{T,Int}()
    for i in 1:length(num_to_key)
      key_to_num[num_to_key[i]] = i
    end
    return new{T}(M, num_to_key, key_to_num)
  end
end

mutable struct MSetPartitionsState
  f::Vector{Int}
  c::Vector{Int}
  u::Vector{Int}
  v::Vector{Int}
  a::Int
  b::Int
  l::Int

  function MSetPartitionsState(MSP::MSetPartitions)
    m = length(MSP.num_to_key)
    n = length(MSP.M)
    f = zeros(Int, n + 1)
    c = zeros(Int, n * m + 1)
    u = zeros(Int, n * m + 1)
    v = zeros(Int, n * m + 1)

    for j in 1:m
      c[j] = j
      u[j] = MSP.M.dict[MSP.num_to_key[j]]
      v[j] = MSP.M.dict[MSP.num_to_key[j]]
    end
    f[1] = 1
    f[2] = m + 1
    a = 1
    b = m + 1
    l = 1

    return new(f, c, u, v, a, b, l)
  end
end

# Handle vector spaces of multivariate polynomials by writing them in the basis
# of the monomials.
mutable struct BasisOfPolynomials{PolyRingT,FieldElemT}
  R::PolyRingT

  # Number the basis monomials, we identify a monomial with its exponent vector
  monomial_to_column::Dict{Vector{Int},Int}

  # Write the polynomials coefficient-wise in the rows of a sparse matrix. The
  # column i contains the coefficients corresponding to the monomial m with
  # monomial_to_column[m] == i.
  M::SMat{FieldElemT}

  function BasisOfPolynomials(R::MPolyRing)
    K = coefficient_ring(R)
    B = new{typeof(R),elem_type(K)}()
    B.R = R
    B.monomial_to_column = Dict{Vector{Int},Int}()
    B.M = sparse_matrix(K)
    return B
  end

  function BasisOfPolynomials(
    R::PolyRingT, polys::Vector{<:MPolyRingElem}
  ) where {PolyRingT<:MPolyRing}
    return BasisOfPolynomials(R, polys, enumerate_monomials(polys))
  end

  function BasisOfPolynomials(
    R::PolyRingT, polys::Vector{<:MPolyRingElem}, monomial_to_column::Dict{Vector{Int},Int}
  ) where {PolyRingT<:MPolyRing}
    if isempty(polys)
      return BasisOfPolynomials(R)
    end

    K = coefficient_ring(R)
    B = new{typeof(R),elem_type(K)}()
    B.R = R

    B.monomial_to_column = monomial_to_column

    M = polys_to_smat(polys, monomial_to_column; copy=true)
    rref!(M; truncate=true)
    B.M = M

    return B
  end
end

# Cache power products (= monomials) of elements in `base` of certain degrees.
mutable struct PowerProductCache{RingType,T}
  # The base ring (needed for empty `base`)
  ring::RingType

  base::Vector{T}

  # Store all power products of degree d
  power_products::Dict{Int,Vector{T}}

  # The exponent vector of a power product w.r.t. `base`
  exponent_vectors::Dict{T,Vector{Int}}

  # Whether the exponent vectors for a certain degree were computed
  exponent_vectors_known::Dict{Int,Bool}

  # The last entry of `base` involved in the power product
  last_factor::Dict{T,Int}

  function PowerProductCache(R::S, base::Vector{T}) where {S<:Ring,T<:RingElem}
    power_products = Dict{Int,Vector{T}}()
    exponent_vectors = Dict{T,Vector{Int}}()
    exponent_vectors_known = Dict{Int,Bool}()
    last_factor = Dict{T,Int}()
    return new{typeof(R),T}(
      R, copy(base), power_products, exponent_vectors, exponent_vectors_known, last_factor
    )
  end
end

# These are objects that carry information about a linearly reductive group.
# As of now it is only implemented for SLn, its direct products and tensors.
mutable struct LinearlyReductiveGroup
  field::Field #characteristic zero. implement check?
  group::Tuple{Symbol,Int}
  defining_ideal::MPolyIdeal
  reynolds_operator::Function
  canonical_representation::MatElem

  function LinearlyReductiveGroup(sym::Symbol, m::Int, fld::Field) #have not decided the representation yet
    @req sym === :SL && characteristic(fld) == 0 "Only SL in characteristic 0 is implemented so far"
    R, _ = polynomial_ring(fld, :z => (1:m, 1:m); cached=false)
    return LinearlyReductiveGroup(sym, m, R)
  end

  function LinearlyReductiveGroup(sym::Symbol, m::Int, pring::MPolyRing) #the ring input is the group ring
    G = new()
    fld = base_ring(pring)
    @req sym === :SL && characteristic(fld) == 0 "Only SL in characteristic 0 is implemented so far"
    G.field = fld
    @req m^2 == ngens(pring) "ring not compatible"
    G.group = (sym, m)
    G.reynolds_operator = reynolds_slm
    M = transpose(matrix(pring, m, m, gens(pring)))
    G.canonical_representation = M
    G.defining_ideal = ideal([det(M) - 1])
    #base ring of M has to be the same as the representation matrix when that is created later.
    return G
  end

  function LinearlyReductiveGroup(I::MPolyIdeal) #defined by just the ideal
    #no checks
    G = new()
    G.defining_ideal = I
    G.field = base_ring(base_ring(I))
    return G
  end
end

# Objects of type LinearlyReductiveGroup can be embedded in GLn (for some n) via
# a representation. This defines the action on a vector space.
# We set up an object RepresentationLinearlyReductiveGroup that carries information
# about this representation.
mutable struct RepresentationLinearlyReductiveGroup
  group::LinearlyReductiveGroup
  rep_mat::MatElem
  reynolds_v::Function

  #stores if the representation is on symmetric forms, and of which degree.
  sym_deg::Tuple{Bool,Int}

  #representation of group G over symmetric degree d
  function RepresentationLinearlyReductiveGroup(G::LinearlyReductiveGroup, d::Int)
    R = new()
    R.group = G
    R.rep_mat = _rep_mat(G, d)
    R.sym_deg = (true, d)
    R.reynolds_v = reynolds_v_slm
    return R
  end

  #matrix M is the representation matrix. does not check M.
  function RepresentationLinearlyReductiveGroup(G::LinearlyReductiveGroup, M::MatElem)
    @req base_ring(M) == base_ring(defining_ideal(G)) "Defining ideal and representation matrix must have same parent ring"
    R = new()
    R.group = G
    R.rep_mat = M
    R.sym_deg = (false, 0)
    if group_type(G) == :SL
      R.reynolds_v = reynolds_v_slm
    end
    return R
  end
end

# Invariant rings of linearly reductive groups
@attributes mutable struct RedGroupInvarRing{FldT,PolyRingElemT,PolyRingT}
  field::FldT
  poly_ring::PolyRingT # graded

  group::LinearlyReductiveGroup
  representation::RepresentationLinearlyReductiveGroup

  reynolds_operator::Function

  fundamental::Vector{PolyRingElemT}
  presentation::MPolyAnyMap{MPolyQuoRing{PolyRingElemT},PolyRingT,Nothing,PolyRingElemT}

  #Invariant ring of reductive group G (in representation R), no other input.
  function RedGroupInvarRing(R::RepresentationLinearlyReductiveGroup) #here G already contains information n and rep_mat
    G = group(R)
    K = base_ring(G)
    n = ncols(R.rep_mat)
    poly_ring, _ = graded_polynomial_ring(K, :X => 1:n; cached=false)
    z = new{typeof(K),elem_type(poly_ring),typeof(poly_ring)}()
    z.representation = R
    z.group = G
    z.field = K
    z.poly_ring = poly_ring
    if isdefined(group(R), :group)
      z.reynolds_operator = reynolds_v_slm
    end
    return z
  end

  #to compute invariant ring ring^G where G is the reductive group of R.
  function RedGroupInvarRing(R::RepresentationLinearlyReductiveGroup, ring::MPolyDecRing)
    n = ncols(R.rep_mat)
    n == ngens(ring) || error("The given polynomial ring is not compatible.")
    G = group(R)
    K = base_ring(G)
    z = new{typeof(K),elem_type(ring),typeof(ring)}()
    z.representation = R
    z.group = G
    z.field = K
    z.poly_ring = ring
    if isdefined(group(R), :group)
      z.reynolds_operator = reynolds_v_slm
    end
    return z
  end
end

