#computing the graph Gamma from Derksens paper
function image_ideal(G::LinearlyReductiveGroup, rep_mat::MatElem)
  R = base_ring(rep_mat)
  n = ncols(rep_mat)
  if isdefined(G, :group)
    m = (group_dim(G))^2
  else
    m = ngens(base_ring(defining_ideal(G)))
  end
  mixed_ring_xy, x, y, zz = polynomial_ring(
    base_ring(G), :x => 1:n, :y => 1:n, :zz => 1:m; cached=false
  )
  ztozz = hom(R, mixed_ring_xy, zz)
  genss = [ztozz(f) for f in gens(defining_ideal(G))]
  #rep_mat in the new ring
  new_rep_mat = map_entries(ztozz, rep_mat)
  new_vars = new_rep_mat * x
  ideal_vect = y - new_vars
  ideal_vect = vcat(ideal_vect, genss)
  return ideal(mixed_ring_xy, ideal_vect), new_rep_mat
end

#computing I_{\Bar{B}}
function proj_of_image_ideal(G::LinearlyReductiveGroup, rep_mat::MatElem)
  W = image_ideal(G, rep_mat)
  mixed_ring_xy = base_ring(W[2])
  n = ncols(rep_mat)
  return eliminate(W[1], gens(mixed_ring_xy)[((2 * n) + 1):end]), W[2]
end

#this function gets the null cone ideal, given by a minimal generating set.
#the generators may or may not be invariant.
#to do this we evaluate what is returned from proj_of_image_ideal at y = 0 
#ie at gens(basering)[n+1:2*n] = [0 for i in 1:n]
function _null_cone_ideal(X::MPolyIdeal, n::Int)
  mixed_ring_xy = base_ring(X)
  #evaluate at gens(mixed_ring_xy)[n+1:2*n] = 0
  xyz = gens(mixed_ring_xy)
  V = vcat(xyz[1:n], [0 for i in 1:n], xyz[(2 * n + 1):end])
  ev_gbasis = [evaluate(f, V) for f in gens(X)]
  #grading starts here. In the end, our invariant ring is graded.
  mixed_ring_graded, _ = grade(mixed_ring_xy)
  mapp = hom(mixed_ring_xy, mixed_ring_graded, gens(mixed_ring_graded))
  I = ideal(mixed_ring_graded, elem_type(mixed_ring_graded)[mapp(f) for f in ev_gbasis])
  # the ring is passed as there are no generators if I is zero
  return ideal(mixed_ring_graded, minimal_generating_set(I))
end

# Computing the invariant generators of the null cone by applying reynolds
# operator to gens(I). This is done in K[X,Y] (basering(I)).
# The elements returned will be in the polynomial K[X] (ringg).
function inv_generators(
  I::MPolyIdeal,
  G::LinearlyReductiveGroup,
  ringg::MPolyRing,
  M::MatElem,
  reynolds_function::Function,
)
  genss = gens(I)
  if length(genss) == 0
    return Vector{elem_type(ringg)}()
  end

  #we need the representation matrix and determinant of group matrix to be in basering(I)
  mixed_ring_xy = parent(genss[1])
  R = base_ring(M)
  n = ncols(M)
  m = G.group[2]
  xyz = gens(mixed_ring_xy)
  mapp = hom(R, mixed_ring_xy, xyz)
  new_rep_mat = matrix(mixed_ring_xy, n, n, [mapp(M[i, j]) for i in 1:n, j in 1:n])
  det_ = det(G.canonical_representation)
  mapp_ = hom(parent(det_), mixed_ring_xy, xyz[((2 * n) + 1):end])
  new_det = mapp_(det_)

  #now we apply reynolds operator to genss
  if group_type(G) === :SL #TODO other types of reductive groups
    new_gens_wrong_ring = [reynolds_function(g, new_rep_mat, new_det, m) for g in genss]
  else
    return nothing
  end

  #map them to the required ring, ringg.
  img_genss = vcat(gens(ringg), Hecke.zeros_array(ringg, length(xyz) - n))
  mixed_to_ring = hom(mixed_ring_xy, ringg, img_genss)
  new_gens = Vector{elem_type(ringg)}()
  for elemm in new_gens_wrong_ring
    if !is_zero(elemm)
      push!(new_gens, mixed_to_ring(elemm))
    end
  end

  #remove ugly coefficients:
  return map(_remove_content, new_gens)
end

# Over QQ, scale f by a positive number such that its coefficients become
# coprime integers.
_remove_content(f::MPolyRingElem) = f

function _remove_content(f::MPolyRingElem{QQFieldElem})
  c = reduce(gcd, coefficients(f); init=zero(QQ))
  return is_zero(c) ? f : inv(c) * f
end

# The Reynolds operator for SLm acting via new_rep_mat.
function reynolds_v_slm(
  elem::MPolyDecRingElem, new_rep_mat::MatElem, new_det::MPolyDecRingElem, m::Int
)
  mixed_ring_xy = parent(elem)
  n = ncols(new_rep_mat)
  new_vars = new_rep_mat * gens(mixed_ring_xy)[1:n]
  # new_vars need not be homogeneous, so this is not a map of graded rings
  sum_ = evaluate(elem, vcat(new_vars, [mixed_ring_xy() for i in 1:(n + m^2)]))

  # The Omega process applies to one degree in the z_ij at a time; the parts of
  # degree not divisible by m are mapped to 0.
  res = mixed_ring_xy()
  for (t, f) in _components_by_z_degree(sum_, m)
    is_divisible_by(t, m) || continue
    res += reynolds_slm(f, new_det, divexact(t, m))
  end
  return res
end

# Reynolds operator for SLm using Cayleys Omega process
function reynolds_slm(elem::MPolyRingElem, det_::MPolyRingElem, p::Int)
  num = omegap_(p, det_, elem)
  den = omegap_(p, det_, det_^p)
  if !(denominator(num//den) == 1)
    error("denominator of reynolds not rational")
  end
  return numerator(num//den)
end

# Split elem into its homogeneous components with respect to the degree in the
# z_ij, which are the last m^2 variables of the ring.
function _components_by_z_degree(elem::MPolyDecRingElem, m::Int)
  R = parent(elem)
  n = ngens(R) - m^2
  ctxs = Dict{Int,MPolyBuildCtx}()
  for (c, e) in zip(coefficients(elem), exponents(elem))
    ctx = get!(() -> MPolyBuildCtx(R), ctxs, sum(@view e[(n + 1):end]))
    push_term!(ctx, c, e)
  end
  return Dict(t => finish(ctx) for (t, ctx) in ctxs)
end

function omegap_(p::Int, det_::MPolyDecRingElem, f::MPolyDecRingElem)
  parent(det_) == parent(f) || error("Omega process ring error")
  action_ring = parent(det_)
  monos = collect(monomials(det_))
  coeffs = collect(coefficients(det_))
  for i in 1:p
    h = action_ring()
    for i in 1:length(monos)
      exp_vect = exponent_vector(monos[i], 1)
      x = f
      for i in 1:length(exp_vect), j in 1:exp_vect[i]
        x = derivative(x, i)
        iszero(x) && break
      end
      h += coeffs[i] * x
    end
    f = h
  end
  return f
end

# Return the image of elem under the reynolds operator of group with representation X
function reynolds_operator(X::RepresentationLinearlyReductiveGroup, elem::MPolyRingElem)
  group_type(group(X)) === :SL || error("Only implemented for SLm")
  vector_ring = parent(elem)
  G = X.group
  n = ngens(vector_ring)
  n == ncols(X.rep_mat) || error("group not compatible with element")
  m = group_dim(G)
  R, _ = graded_polynomial_ring(
    base_ring(G), :x => 1:n, :y => 1:n, :z => (1:m, 1:m); cached=false
  )
  map1 = hom(vector_ring, R, gens(R)[1:n])
  new_elem = map1(elem)
  group_ring = base_ring(X.rep_mat)
  map2 = hom(group_ring, R, gens(R)[(2 * n + 1):(2 * n + m^2)])
  new_rep_mat = map_entries(map2, X.rep_mat)
  new_det = map2(det(G.canonical_representation))
  f = X.reynolds_v(new_elem, new_rep_mat, new_det, m)
  reverse_map = hom(R, vector_ring, vcat(gens(vector_ring), [0 for i in 1:(n + m^2)]))
  return reverse_map(f)
end

