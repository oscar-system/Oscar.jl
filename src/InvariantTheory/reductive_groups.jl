@doc raw"""
    affine_algebra(RG::RedGroupInvarRing)

Return the invariant ring `RG` as an affine algebra (this amounts to compute the algebra syzygies among the fundamental invariants of `RG`).

In addition, if `A` is this algebra, and `R` is the polynomial ring of which `RG` is a subalgebra,
return the inclusion homomorphism  `A` $\hookrightarrow$ `R` whose image is `RG`.

# Examples
```jldoctest
julia> G = linearly_reductive_group(:SL, 2, QQ);

julia> r = representation_on_forms(G, 2);

julia> S, x = graded_polynomial_ring(QQ, :x => 1:3);

julia> RG = invariant_ring(S, r);

julia> A, AtoS = affine_algebra(RG)
(Quotient of multivariate polynomial ring by ideal (0), Hom: A -> S)
```
"""
function affine_algebra(R::RedGroupInvarRing)
  if !isdefined(R, :presentation)
    V = fundamental_invariants(R)
    s = length(V)
    weights_ = zeros(Int, s)
    for i in 1:s
      weights_[i] = total_degree(V[i])
    end
    S, _ = graded_polynomial_ring(
      coefficient_ring(R), :t => 1:s; weights=weights_, cached=false
    )
    R_ = polynomial_ring(R)
    StoR = hom(S, R_, V)
    I = kernel(StoR)
    Q, StoQ = quo(S, I)
    QtoR = hom(Q, R_, V)
    R.presentation = QtoR
  end
  return domain(R.presentation), R.presentation
end

# Algorithm 4.5.1 in [DK15]
# Compute generators of the invariant ring without a Reynolds operator: the
# invariants of the degrees of the generators of the null cone ideal I generate
# the invariant ring. Here b is the ideal returned by proj_of_image_ideal and
# ringg is the ring in which we must return the invariants.
function inv_gens_no_reynolds(I::MPolyIdeal, b::MPolyIdeal, ringg::MPolyRing)
  n = ngens(ringg)
  mixed_ring_xy = base_ring(b)
  phi = hom(
    mixed_ring_xy, ringg, vcat(gens(ringg), [0 for i in (n + 1):ngens(mixed_ring_xy)])
  )

  degrees = sort!(unique!(map(total_degree, gens(I))))
  ans_vect = Vector{elem_type(ringg)}()
  for d in degrees
    append!(ans_vect, map(phi, basis_no_reynolds(d, n, b)))
  end
  return ans_vect
end

# Compute a K-basis of the invariants of degree d in the first n variables x of
# base_ring(b), a ring with variables x(1:n), y(1:n) and zz(1:?).
# A polynomial h in x is invariant if and only if h(x) - h(y) is in b.
function basis_no_reynolds(d::Int, n::Int, b::MPolyIdeal)
  mixed_ring = base_ring(b)
  xyz = gens(mixed_ring)
  x_to_y = hom(mixed_ring, mixed_ring, vcat(xyz[(n + 1):(2 * n)], xyz[(n + 1):end]))

  H = collect(monomials_of_degree(mixed_ring, d, 1:n))
  polys = normal_form([m - x_to_y(m) for m in H], b)

  #finding the generators of the kernel space
  V, VtoPoly = vector_space(base_ring(mixed_ring), polys)
  W = vector_space(base_ring(mixed_ring), length(polys))
  h = hom(W, V, [Oscar.preimage(VtoPoly, f) for f in polys])
  K, KtoW = kernel(h)
  alpha = KtoW.(gens(K))
  ans = Vector{elem_type(mixed_ring)}()
  for i in 1:length(alpha)
    pol = mixed_ring()
    for j in 1:length(alpha[i].v)
      pol += alpha[i][j] * H[j]
    end
    push!(ans, pol)
  end
  return ans
end
