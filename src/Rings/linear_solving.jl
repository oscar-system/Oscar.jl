struct ModuleSolveTrait <: AbstractAlgebra.Solve.MatrixNormalFormTrait end

AbstractAlgebra.Solve.matrix_normal_form_type(::Union{MPolyRing, MPolyQuoRing, MPolyLocRing, MPolyQuoLocRing}) = ModuleSolveTrait()

function _module_solve_map(A::MatElem)
  R = base_ring(A)
  F = free_module(R, nrows(A); cached = false)
  G = free_module(R, ncols(A); cached = false)
  return hom(F, G, A)
end

# - Module maps and their image/kernel atributes play the role of reduced matrices
#   for ModuleSolveTrait.
# - image_module(h) caches the image as an attribute of the FreeModuleHom obejct.
@attr FreeModuleHom{FreeMod{T}, FreeMod{T}, Nothing} function AbstractAlgebra.Solve._init_reduce(
  C::AbstractAlgebra.Solve.SolveCtx{T, ModuleSolveTrait},
) where T
  h = _module_solve_map(matrix(C))
  image_module(h)
  return h
end

@attr FreeModuleHom{FreeMod{T}, FreeMod{T}, Nothing} function AbstractAlgebra.Solve._init_reduce_transpose(
  C::AbstractAlgebra.Solve.SolveCtx{T, ModuleSolveTrait},
) where T
  h = _module_solve_map(transpose(matrix(C)))
  image_module(h)
  return h
end

function _module_solve_map(
  C::AbstractAlgebra.Solve.SolveCtx{T, ModuleSolveTrait}, side::Symbol,
) where T
  if side === :left
    return AbstractAlgebra.Solve._init_reduce(C)
  end
  return AbstractAlgebra.Solve._init_reduce_transpose(C)
end

function _module_kernel(h)
  F = domain(h)
  R = base_ring(F)
  K, KtoF = kernel(h)
  if ngens(K) == 0
    return zero_matrix(R, 0, rank(F))
  end
  return reduce(vcat, dense_row.((coordinates.(KtoF.(gens(K))))::Vector{sparse_row_type(R)}, rank(F)))
end

function _can_solve_with_module_map(h, b::MatElem, task::Symbol)
  F = domain(h)
  G = codomain(h)
  R = base_ring(F)
  imh = image_module(h)
  # - imh is the submodue of G generated by the images of the basis of F.
  # - Its coordinates are the coefficents of a preimage under h.
  sol = zero_matrix(R, nrows(b), rank(F))
  for i in 1:nrows(b)
    c = G(b[i, :])
    if !(c in imh)
      return false, sol, sol
    end
    if task !== :only_check
      sol[i, :] = dense_row(coordinates(c, imh)::sparse_row_type(R), rank(F))
    end
  end
  if task !== :with_kernel
    return true, sol, sol
  end
  return true, sol, _module_kernel(h)
end

function AbstractAlgebra.Solve._can_solve_internal_no_check(
  ::ModuleSolveTrait, A::MatElem{T}, b::MatElem{T}, task::Symbol; side::Symbol,
) where T
  if side === :right
    fl, X, K = _can_solve_with_module_map(_module_solve_map(transpose(A)), transpose(b), task)
    return fl, transpose(X), transpose(K)
  end
  return _can_solve_with_module_map(_module_solve_map(A), b, task)
end

function AbstractAlgebra.Solve._can_solve_internal_no_check(
  ::ModuleSolveTrait,
  C::AbstractAlgebra.Solve.SolveCtx{T, ModuleSolveTrait},
  b::MatElem{T},
  task::Symbol;
  side::Symbol,
) where T
  # - Compute kernels through kernel(C) below.
  # - The resulting matrix is stored in C.kernel_left or C.kernel_right.
  # - Asking the helper for it here would compute a kernel that is immediatly discarded.
  solve_task = task === :with_kernel ? :with_solution : task
  if side === :right
    fl, X, _K = _can_solve_with_module_map(_module_solve_map(C, side), transpose(b), solve_task)
    sol = transpose(X)
    _K = transpose(_K)
  else
    fl, sol, _K = _can_solve_with_module_map(_module_solve_map(C, side), b, solve_task)
  end
  if fl && task === :with_kernel
    return true, sol, kernel(ModuleSolveTrait(), C; side)
  end
  return fl, sol, _K
end

function AbstractAlgebra.kernel(::ModuleSolveTrait, A::MatElem; side::Symbol = :left)
  AbstractAlgebra.Solve.check_option(side, [:right, :left], "side")
  if side === :right
    return transpose(_module_kernel(_module_solve_map(transpose(A))))
  end
  return _module_kernel(_module_solve_map(A))
end

function AbstractAlgebra.kernel(
  ::ModuleSolveTrait,
  C::AbstractAlgebra.Solve.SolveCtx{T, ModuleSolveTrait};
  side::Symbol = :left,
) where T
  AbstractAlgebra.Solve.check_option(side, [:right, :left], "side")
  if side === :right
    if !isdefined(C, :kernel_right)
      C.kernel_right = transpose(_module_kernel(_module_solve_map(C, side)))
    end
    return C.kernel_right
  end
  if !isdefined(C, :kernel_left)
    C.kernel_left = _module_kernel(_module_solve_map(C, side))
  end
  return C.kernel_left
end

struct LaurentSolveTrait <: AbstractAlgebra.Solve.MatrixNormalFormTrait end

AbstractAlgebra.Solve.matrix_normal_form_type(::AbstractAlgebra.Generic.LaurentMPolyWrapRing) = LaurentSolveTrait()

function _can_solve_laurent(f, A, AA, b, task::Symbol; side::Symbol)
  bb = map_entries(f, b)
  fl, sol, K = AbstractAlgebra.Solve._can_solve_internal_no_check(
    AbstractAlgebra.Solve.matrix_normal_form_type(AA), AA, bb, task; side,
  )
  if task === :only_check
    return fl::Bool, A, A
  elseif task === :with_solution
    return fl::Bool, preimage.(Ref(f), sol)::typeof(A), A
  else
    return fl::Bool, preimage.(Ref(f), sol)::typeof(A), preimage.(Ref(f), K)::typeof(b)
  end
end

function AbstractAlgebra.Solve._can_solve_internal_no_check(
  ::LaurentSolveTrait, A::MatElem{T}, b::MatElem{T}, task::Symbol; side::Symbol,
) where T
  R = base_ring(A)
  f = Oscar._polyringquo(R)
  AA = map_entries(f, A)
  return _can_solve_laurent(f, A, AA, b, task; side)
end

@attr Tuple{_LaurentMPolyBackend, AbstractAlgebra.Solve.SolveCtx} function AbstractAlgebra.Solve._init_reduce(
  C::AbstractAlgebra.Solve.SolveCtx{T, LaurentSolveTrait},
) where T
  f = Oscar._polyringquo(base_ring(C))
  AA = map_entries(f, matrix(C))
  return f, solve_init(AA)
end

function AbstractAlgebra.Solve._init_reduce_transpose(
  C::AbstractAlgebra.Solve.SolveCtx{T, LaurentSolveTrait},
) where T
  return AbstractAlgebra.Solve._init_reduce(C)
end

function _laurent_solve_data(
  C::AbstractAlgebra.Solve.SolveCtx{T, LaurentSolveTrait}, side::Symbol,
) where T
  if side === :right
    return AbstractAlgebra.Solve._init_reduce_transpose(C)
  end
  return AbstractAlgebra.Solve._init_reduce(C)
end

function AbstractAlgebra.Solve._can_solve_internal_no_check(
  ::LaurentSolveTrait,
  C::AbstractAlgebra.Solve.SolveCtx{T, LaurentSolveTrait},
  b::MatElem{T},
  task::Symbol;
  side::Symbol,
) where T
  f, inner_C = _laurent_solve_data(C, side)
  return _can_solve_laurent(f, matrix(C), inner_C, b, task; side)
end

function AbstractAlgebra.kernel(::LaurentSolveTrait, A::MatElem; side::Symbol = :left)
  AbstractAlgebra.Solve.check_option(side, [:right, :left], "side")
  f = Oscar._polyringquo(base_ring(A))
  K = kernel(map_entries(f, A); side)
  return preimage.(Ref(f), K)::typeof(A)
end

function AbstractAlgebra.kernel(
  ::LaurentSolveTrait,
  C::AbstractAlgebra.Solve.SolveCtx{T, LaurentSolveTrait};
  side::Symbol = :left,
) where T
  AbstractAlgebra.Solve.check_option(side, [:right, :left], "side")
  f, inner_C = _laurent_solve_data(C, side)
  if side === :right
    if !isdefined(C, :kernel_right)
      C.kernel_right = preimage.(Ref(f), kernel(inner_C; side))
    end
    return C.kernel_right
  end
  if !isdefined(C, :kernel_left)
    C.kernel_left = preimage.(Ref(f), kernel(inner_C; side))
  end
  return C.kernel_left
end
