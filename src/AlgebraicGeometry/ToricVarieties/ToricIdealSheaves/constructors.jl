# Toric Cox-ring ideal sheaves.

@doc raw"""
    ideal_sheaf(X::NormalToricVariety, I::MPolyIdeal)

Let $X_\Sigma$ be a normal toric variety with Cox ring $S$. Return the
ideal sheaf associated with a homogeneous ideal $I\subseteq S$.

Every maximal cone of $\Sigma$ must have full dimension in the lattice
$N$; equivalently, $\Sigma$ must be pure and full-dimensional. Smoothness
and completeness are not required, and $X_\Sigma$ may be affine.

This method accepts objects of type `NormalToricVariety`. For a cone `C`,
use `normal_toric_variety(C)` rather than
`affine_normal_toric_variety(C)`, whose return type is currently unsupported.

Evaluation is lazy: restricting the sheaf to an affine toric chart requires
dehomogenizing the Cox ideal, which may involve expensive computations.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2)
Normal toric variety

julia> x, y, z = gens(cox_ring(X));

julia> I = ideal(cox_ring(X), x^2 - y*z);

julia> II = ideal_sheaf(X, I);

julia> II(affine_charts(X)[1])
Ideal generated by
  x_1_1^2 - x_2_1
```
"""
function ideal_sheaf(X::NormalToricVariety, I::MPolyIdeal)
  @req all(is_fulldimensional, maximal_cones(X)) "A maximal cone is not full-dimensional"
  @req base_ring(I) === cox_ring(X) "The ideal must belong to cox_ring(X)"
  return ToricIdealSheafFromCoxRingIdeal(X, I)
end

@doc raw"""
    ideal_sheaf(td::ToricDivisor)

Return the ideal sheaf associated with the effective Cartier toric divisor
`td`. The defining homogeneous Cox-ring monomial has exponents given by the
coefficients of `td`. The corresponding ideal sheaf is computed lazily.

The ambient toric variety must satisfy the same restrictions as for
`ideal_sheaf(X, I)`. The divisor must be effective and Cartier, although its
individual prime components need not be Cartier.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2)
Normal toric variety

julia> D = toric_divisor(X, [1, 0, 0])
Torus-invariant, prime divisor on a normal toric variety

julia> J = ideal_sheaf(D);

julia> sum(isone(J(U)) for U in affine_charts(X))
1
```
"""
@attr AbsIdealSheaf function ideal_sheaf(td::ToricDivisor)
  @req is_cartier(td) "The toric divisor must be Cartier"
  @req is_effective(td) "The toric divisor must be effective"

  X = toric_variety(td)
  S = cox_ring(X)
  f = one(S)
  for (x, a) in zip(gens(S), coefficients(td))
    f *= x^Int(a)
  end
  return ideal_sheaf(X, ideal(S, f))
end

# Compatibility constructor returning the eager IdealSheaf representation.
# Public-facing code should use ideal_sheaf(X, I) instead.
function IdealSheaf(X::NormalToricVariety, I::MPolyIdeal)
  II = ideal_sheaf(X, I)
  local_ideals = IdDict{AbsAffineScheme,Ideal}()
  for U in affine_charts(X)
    local_ideals[U] = II(U)
  end
  return IdealSheaf(X, local_ideals; check=false)
end

@doc raw"""
    ideal_sheaf(X::NormalToricVariety, tau::Cone)

Return the ideal sheaf defining the orbit closure associated to the cone
`tau` of the fan of `X` under the orbit-cone correspondence.

The defining ideal in the Cox ring is generated by the variables
corresponding to the rays of `tau`. For the zero cone, the ideal is zero.
The ambient toric variety must satisfy the same restrictions as for
`ideal_sheaf(X, I)`.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2)
Normal toric variety

julia> tau = first(cones(polyhedral_fan(X), 1));

julia> ideal_sheaf(X, tau) isa Oscar.ToricIdealSheafFromCoxRingIdeal
true
```
"""
function ideal_sheaf(X::NormalToricVariety, tau::Cone)
  Sigma = polyhedral_fan(X)
  @req tau in Sigma "The cone must belong to the fan of the toric variety"

  S = cox_ring(X)
  if dim(tau) == 0
    return ideal_sheaf(X, ideal(S, zero(S)))
  end

  fan_rays = collect(rays(Sigma))
  indices = [findfirst(==(ray), fan_rays) for ray in rays(tau)]
  @assert all(!isnothing, indices)
  return ideal_sheaf(X, ideal(S, [gens(S)[i] for i in indices]))
end

function _dehomogenize_to_chart(X::NormalToricVarietyType, I::MPolyIdeal, k::Int)
  # Cox-Little-Schenck, Proposition 5.2.10 and Exercise 5.2.5.
  U = affine_charts(X)[k]
  R = OO(U)
  iszero(I) && return ideal(R, zero(R))
  isone(I) && return ideal(R, one(R))

  S = cox_ring(X)
  ray_matrix = matrix(ZZ, rays(X))
  ray_indices_sigma = ray_indices(maximal_cones(X))[k, :]
  inverted_variables = [x for (i, x) in enumerate(gens(S)) if !ray_indices_sigma[i]]
  S_loc = if isempty(inverted_variables)
    S
  else
    localization(S, MPolyPowersOfElement(S, inverted_variables))[1]
  end

  # The chart coordinates are invariant monomials from the Hilbert basis
  # of the dual cone, mapped into the localization of the Cox ring.
  hb = hilbert_basis(U)
  x = gens(S_loc)
  chart_monomials = [one(S_loc) for _ in 1:nrows(hb)]
  for j in 1:nrows(hb)
    for i in 1:nrows(ray_matrix)
      chart_monomials[j] *= x[i]^Int(dot(hb[j, :], ray_matrix[i, :]))
    end
  end

  # The Cox variables outside the maximal cone become units on this chart.
  indices = [i for i in row(maximal_cones(IncidenceMatrix, X), k)]
  help_ring, x_rho = polynomial_ring(QQ, "x#" => indices)
  images = [one(help_ring) for _ in 1:n_rays(X)]
  for (j, i) in enumerate(indices)
    images[i] = x_rho[j]
  end
  dehomogenization = hom(S_loc, help_ring, images; check=false)

  # The local ideal is the kernel of the induced map to the quotient
  # of the chart's dehomogenized Cox-ring ideal.
  I_dehom = dehomogenization(I)
  A, pr = quo(help_ring, I_dehom)
  images_on_chart = pr.(dehomogenization.(chart_monomials))
  return kernel(hom(R, A, images_on_chart; check=false))
end
