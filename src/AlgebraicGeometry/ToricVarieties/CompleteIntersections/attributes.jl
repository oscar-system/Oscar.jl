# Attributes of toric complete-intersection presentations.

_complete_intersection_presentation(Y::CompleteIntersectionInToricVariety) = Y
_complete_intersection_presentation(Y::HypersurfaceInToricVariety) = Y.presentation

# Required by the AbsCoveredScheme forwarding interface.
underlying_scheme(Y::AbsCompleteIntersectionInToricVariety) = covered_scheme(Y)

@doc raw"""
    toric_variety(Y::AbsCompleteIntersectionInToricVariety)

Return the ambient normal toric variety of `Y`.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2);

julia> x = first(gens(cox_ring(X)));

julia> H = hypersurface_in_toric_variety(X, x);

julia> toric_variety(H) === X
true
```
"""
toric_variety(Y::AbsCompleteIntersectionInToricVariety) =
  _complete_intersection_presentation(Y).ambient

@doc raw"""
    defining_equations(Y::AbsCompleteIntersectionInToricVariety)

Return independent copies of the chosen homogeneous Cox-ring equations of `Y`.
Modifying a returned polynomial does not change the stored presentation.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2);

julia> x, y, z = gens(cox_ring(X));

julia> C = complete_intersection_in_toric_variety(X, [x, y]);

julia> defining_equations(C) == [x, y]
true
```
"""
defining_equations(Y::AbsCompleteIntersectionInToricVariety) =
  [copy(f) for f in _complete_intersection_presentation(Y).equations]

@doc raw"""
    defining_equation(Y::HypersurfaceInToricVariety)

Return an independent copy of the homogeneous Cox-ring equation defining the
hypersurface `Y`.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2);

julia> x = first(gens(cox_ring(X)));

julia> H = hypersurface_in_toric_variety(X, x^2);

julia> defining_equation(H) == x^2
true
```
"""
defining_equation(Y::HypersurfaceInToricVariety) = only(defining_equations(Y))

# Divisor classes are derived from the equations; inconsistent class data cannot
# be supplied through an alternate constructor.

@doc raw"""
    defining_divisor_classes(Y::AbsCompleteIntersectionInToricVariety)

Return the divisor classes of the chosen Cox-ring equations.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2);

julia> x, y, z = gens(cox_ring(X));

julia> C = complete_intersection_in_toric_variety(X, [x, y]);

julia> defining_divisor_classes(C) == fill(toric_divisor_class(X, degree(x)), 2)
true
```
"""
defining_divisor_classes(Y::AbsCompleteIntersectionInToricVariety) = [
  toric_divisor_class(toric_variety(Y), degree(f)) for f in defining_equations(Y)
]

@doc raw"""
    defining_divisor_class(Y::HypersurfaceInToricVariety)

Return the divisor class of the single defining equation of `Y`.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2);

julia> x = first(gens(cox_ring(X)));

julia> H = hypersurface_in_toric_variety(X, x^2);

julia> defining_divisor_class(H) == toric_divisor_class(X, degree(x^2))
true
```
"""
defining_divisor_class(Y::HypersurfaceInToricVariety) =
  only(defining_divisor_classes(Y))

@doc raw"""
    defining_ideal(Y::CompleteIntersectionInToricVariety)

Return the ideal generated by the chosen equations in the ambient Cox ring.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2);

julia> x, y, z = gens(cox_ring(X));

julia> C = complete_intersection_in_toric_variety(X, [x, y]);

julia> defining_ideal(C) == ideal(cox_ring(X), [x, y])
true
```
"""
@attr MPolyIdeal defining_ideal(Y::CompleteIntersectionInToricVariety) =
  ideal(cox_ring(toric_variety(Y)), defining_equations(Y))
defining_ideal(Y::HypersurfaceInToricVariety) =
  defining_ideal(_complete_intersection_presentation(Y))

@doc raw"""
    closed_embedding(Y::CompleteIntersectionInToricVariety)

Return the closed embedding of the hypersurface or complete intersection into
its ambient toric variety.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2);

julia> x = first(gens(cox_ring(X)));

julia> H = hypersurface_in_toric_variety(X, x);

julia> codomain(Oscar.closed_embedding(H)) === X
true
```
"""
@attr CoveredClosedEmbedding function closed_embedding(
  Y::CompleteIntersectionInToricVariety
)
  X = toric_variety(Y)
  return CoveredClosedEmbedding(X, ideal_sheaf(X, defining_ideal(Y)))
end
closed_embedding(Y::HypersurfaceInToricVariety) =
  closed_embedding(_complete_intersection_presentation(Y))

@doc raw"""
    covered_scheme(Y::AbsCompleteIntersectionInToricVariety)

Return the covered scheme associated with `Y`.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2);

julia> x = first(gens(cox_ring(X)));

julia> H = hypersurface_in_toric_variety(X, x);

julia> domain(Oscar.closed_embedding(H)) === covered_scheme(H)
true
```
"""
covered_scheme(Y::AbsCompleteIntersectionInToricVariety) = domain(closed_embedding(Y))

# Chow classes and intersections of complete-intersection presentations.

@doc raw"""
    fundamental_class(Y::AbsCompleteIntersectionInToricVariety; check_codimension=true)

Return the class of the fundamental cycle of a chosen complete-intersection
presentation in a simplicial (not necessarily complete) toric variety.
The product of the defining divisor classes represents this cycle subject to
the codimension and Cartier conditions.

Empty zero loci are accepted, with zero fundamental class. The codimension
check can be skipped with `check_codimension=false` when the equations are
known to define a complete intersection. Skipping the check also skips
emptiness detection. No reducedness or smoothness condition is imposed.

# Examples
```jldoctest
julia> X = projective_space(NormalToricVariety, 2);

julia> x = first(gens(cox_ring(X)));

julia> H = hypersurface_in_toric_variety(X, x);

julia> fundamental_class(H) == rational_equivalence_class(defining_divisor_class(H))
true
```
"""
function fundamental_class(
  Y::AbsCompleteIntersectionInToricVariety; check_codimension::Bool=true
)
  X = toric_variety(Y)
  @req is_simplicial(X) "Chow classes require a simplicial toric variety"
  if check_codimension
    _check_complete_intersection_presentation(Y; check_codimension=true)
    if is_empty(Y)
      return RationalEquivalenceClass(X, zero(chow_ring(X)))
    end
  else
    P = _complete_intersection_presentation(Y)
    @req !has_attribute(P, :has_expected_codimension) ||
      get_attribute(P, :has_expected_codimension) "The equations are known not to have the expected codimension"
  end
  result = RationalEquivalenceClass(X, one(chow_ring(X)))
  for D in defining_divisor_classes(Y)
    result *= rational_equivalence_class(D)
  end
  return result
end

# Compatibility with cycle-class APIs; `fundamental_class` is the preferred name.
function rational_equivalence_class(
  Y::AbsCompleteIntersectionInToricVariety; check_codimension::Bool=true
)
  return fundamental_class(Y; check_codimension)
end

function Base.:*(ac::RationalEquivalenceClass, Y::AbsCompleteIntersectionInToricVariety)
  @req toric_variety(ac) === toric_variety(Y) "Both objects must have the same ambient variety"
  return ac * fundamental_class(Y)
end
Base.:*(Y::AbsCompleteIntersectionInToricVariety, ac::RationalEquivalenceClass) = ac * Y
