# ---------------------------------------------------------------------------
# The algorithm of Shimoyama and Yokoyama for primary decomposition, see
# `primdecSY` of Singular's `primdec.lib`. It proceeds in two stages:
#  1. pseudo-primary decomposition: if `P_1, ..., P_s` are the minimal primes of
#     `J` and `f_i` is a separator (a polynomial in all `P_j`, `j != i`, but not in
#     `P_i`), then with a generic element `f` of `<f_1, ..., f_s>`
#       J = (J : f_1^oo) ∩ ... ∩ (J : f_s^oo) ∩ (J + <f^k>),
#     and the ideal `J : f_i^oo` is pseudo-primary with radical `P_i`; here
#     `A` is replaced by a generic element of `A`;
#  2. extraction: if `U` is a maximal independent set modulo `P_i` and `h` the lcm
#     of the leading coefficients of a Groebner basis of a pseudo-primary ideal `Q`
#     with respect to a block ordering with `U` last, then `Q : h^oo` is primary
#     and `Q = (Q : h^oo) ∩ (Q + <h^k>)`.
# The remaining ideals are decomposed recursively. In contrast to Singular, the
# minimal primes are computed by the GTZ algorithm and not by characteristic sets.
# ---------------------------------------------------------------------------

# A polynomial lying in all primes of `L` other than the `i`-th one, but not in `L[i]`.
function _pd_separator(L::Vector{<:MPolyIdeal}, i::Int)
  others = [L[j] for j in eachindex(L) if j != i]
  N = length(others) == 1 ? others[1] : intersect(others...)
  for g in gens(N)
    is_zero(g) && continue
    ideal_membership(g, L[i]) || return g
  end
  error("no separator found, the primes are not irredundant")
end

# A generic element `f` of the ideal generated by the separators `seps` such that
# `J : f^oo = J : <seps>^oo`, which is the intersection of the saturations by the
# single separators. Returns `f` and the saturation. A principal ideal is needed
# for the decomposition `J = (J : f^oo) ∩ (J + <f^k>)`.
function _pd_generic_separator(J::MPolyIdeal, seps::Vector)
  R = base_ring(J)
  S = intersect([saturation(J, ideal(R, [f])) for f in seps]...)
  for tries in 1:100
    range = 3 * tries
    f = sum(R(rand(1:range)) * g for g in seps)
    is_subset(S, saturation(J, ideal(R, [f]))) && return f, S
  end
  error("could not find a generic separator (is the field too small?)")
end

# Extract the primary component from the pseudo-primary ideal `Q` with prime
# radical `P`; returns the primary component and the ideals left to be decomposed.
function _pd_extract(Q::MPolyIdeal, P::MPolyIdeal)
  R = base_ring(Q)
  n = ngens(R)
  d = dim(P)
  (d == 0 || d == n) && return Q, typeof(Q)[]
  U = _pd_independent_set(P)
  h = _pd_lead_lcm(Q, U)
  S, _, f, k = _pd_split_by(Q, h)
  k == 0 && return S, typeof(Q)[]
  return S, [Q + ideal(R, [f^k])]
end

@doc raw"""
    primary_decomposition_sy(I::MPolyIdeal) -> Vector{Tuple{MPolyIdeal, MPolyIdeal}}

Compute a primary decomposition of `I` with the algorithm of Shimoyama and
Yokoyama. The result is a vector of pairs `(Q, P)` of a primary component `Q`
and its radical `P`, without redundant components.

# Examples
```jldoctest
julia> R, (x, y, z) = polynomial_ring(QQ, [:x, :y, :z]);

julia> length(primary_decomposition_sy(ideal(R, [x^2, x*y])))
2
```
"""
function primary_decomposition_sy(I::MPolyIdeal)
  T = typeof(I)
  I = _pd_clean(I)
  is_one(I) && return Tuple{T,T}[]
  res = Tuple{T,T}[]
  todo = [I]
  while !isempty(todo)
    J = pop!(todo)
    is_one(J) && continue
    primes = minimal_associated_primes_gtz(J)
    R = base_ring(J)
    if length(primes) == 1
      pseudo = [(J, primes[1])]
    else
      seps = [_pd_separator(primes, i) for i in eachindex(primes)]
      pseudo = [(saturation(J, ideal(R, [f])), P) for (f, P) in zip(seps, primes)]
      f, S = _pd_generic_separator(J, seps)
      _, k = saturation_with_index(J, ideal(R, [f]))
      k > 0 && push!(todo, J + ideal(R, [f^k]))
    end
    for (Q, P) in pseudo
      prim, rest = _pd_extract(Q, P)
      push!(res, (prim, P))
      append!(todo, rest)
    end
  end
  return _pd_irredundant(res)
end
