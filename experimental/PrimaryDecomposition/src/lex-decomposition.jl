# ---------------------------------------------------------------------------
# Decomposition of the extension of an ideal `I` to `K(u)[x']` with Singular's
# `zero_decomp`, as in `newReduction` of `primdec.lib`: a Groebner basis of `I`
# in `K[x, u]` with respect to a block ordering, lexicographical on `x'`, with `x'` before `u`
# is, after discarding the elements whose leading monomial in `x'` is divisible by
# that of another element, a lexicographical Groebner basis over `K(u)`. No
# Groebner basis over `K(u)` and no linear algebra with rational functions is
# needed, and the components are small.
# ---------------------------------------------------------------------------

# Whether Singular's transcendental extension of the coefficient field is available.
function _pd_singular_supported(K)
  K isa QQField && return true
  return characteristic(K) > 0 && degree(K) == 1
end

# The block ordering of `R` with the variables `X` before those in `U`, which is
# lexicographical on `X` and degree reverse lexicographical on `U`. Over `K(u)` only
# the ordering of the variables `X` matters, and a lexicographical ordering on `U`
# makes the Groebner basis computation much more expensive.
function _pd_lex_ordering(R::MPolyRing, X::Vector{Int}, U::Vector{Int})
  return lex(gens(R)[X]) * degrevlex(gens(R)[U])
end

# A Groebner basis of the extension of `I` to `K(u)[x']` with respect to the
# lexicographical ordering of `x'`, as polynomials of `K(u)[x']`.
function _pd_lex_extension_basis(E::_PDExtension, I::MPolyIdeal)
  o = _pd_lex_ordering(E.R, E.X, E.U)
  G = collect(groebner_basis(I; ordering=o))
  lms = [exponent_vector(leading_monomial(g; ordering=o), 1) for g in G]
  keep = Int[]
  for i in eachindex(G)
    xi = lms[i][E.X]
    redundant = false
    for j in eachindex(G)
      j == i && continue
      xj = lms[j][E.X]
      all(xj .<= xi) || continue
      # the element with the smaller power of `u` is kept if the leading monomials in `x'` agree
      if xj != xi || lms[j][E.U] < lms[i][E.U] || (lms[j][E.U] == lms[i][E.U] && j < i)
        redundant = true
        break
      end
    end
    redundant || push!(keep, i)
  end
  return [_pd_to_ext(E, G[i]) for i in keep]
end

# `zero_decomp` is always called with `ch = 0` and only its primary components are
# used: the primes it returns can be wrong, for instance `(x1)` for the component
# `(x1 - x3)^3` with `ch = 1` and the primary ideal itself instead of its radical
# with `ch = 0`. The prime of a component is its radical, computed by Singular.

# Run `f` without Singular's warning about ideals not known to be standard bases.
function _pd_without_sb_warning(f)
  old = Singular.libSingular.set_option("V_NSB", true)
  try
    return f()
  finally
    Singular.libSingular.set_option("V_NSB", old)
  end
end

# The primary components (or the associated primes if `primary` is false) of
# the extension of `I` to `K(u)[x']` together with their radicals, as pairs of
# lists of generators in `K(u)[x']`, computed by Singular's `zero_decomp`, and the
# leading coefficients for the contraction of `I`.
function _pd_zero_decomposition_lex(E::_PDExtension, I::MPolyIdeal; primary::Bool)
  gx = _pd_lex_extension_basis(E, I)
  Jx = ideal(E.Rx, gx)
  Sg = singular_generators(Jx, lex(E.Rx))
  Sg.isGB = true
  SR = base_ring(Sg)
  zero = Singular.Ideal(SR, SR(0))
  res = _pd_without_sb_warning() do
    Singular.LibPrimdec.zero_decomp(Sg, zero, 0)
  end
  # `zero_decomp` does not return reduced bases, which can be much larger
  back(sid) = filter(!is_zero, collect(IdealGens(E.Rx, Singular.std(sid; complete_reduction=true))))
  comps = [(back(res[2k-1]), back(Singular.LibPrimdec.radical(SR, res[2k-1]))) for k in 1:(length(res) ÷ 2)]
  # a lost component would give a wrong contraction, see `_pd_zero_components_complete`
  oX = lex(E.Rx)
  count(gs) = _pd_standard_count(_pd_lex_leads(gs, oX))
  sum(count(Q) for (Q, _) in comps) == count(gx) || error("zero_decomp lost components")
  return comps, _pd_lex_lead_coeffs(E, gx)
end

# `_pd_zero_decomposition_lex`, or `nothing` if Singular cannot extend the coefficient
# field or fails, in which case the native decomposition has to be used.
function _pd_try_zero_decomposition_lex(E::_PDExtension, I::MPolyIdeal; primary::Bool)
  _pd_singular_supported(coefficient_ring(E.R)) || return nothing
  try
    return _pd_zero_decomposition_lex(E, I; primary)
  catch e
    e isa ErrorException || rethrow()
    return nothing
  end
end

# Singular's `zero_decomp` for the ideal of `S` generated by the lexicographical
# basis `gs`, returned as pairs of lists of generators.
function _pd_zero_decomp(S::MPolyRing, gs::Vector; primary::Bool)
  J = ideal(S, gs)
  o = lex(S)
  Sg = singular_generators(J, o)
  Sg.isGB = true
  SR = base_ring(Sg)
  zero = Singular.Ideal(SR, SR(0))
  res = _pd_without_sb_warning() do
    Singular.LibPrimdec.zero_decomp(Sg, zero, 0)
  end
  back(sid) = filter(!is_zero, collect(IdealGens(S, Singular.std(sid; complete_reduction=true))))
  return [(back(res[2k-1]), back(Singular.LibPrimdec.radical(SR, res[2k-1]))) for k in 1:(length(res) ÷ 2)]
end

# The primary components (or the associated primes if `primary` is false) of a
# zero-dimensional ideal `I` of `K[x]` together with their radicals, as pairs of
# ideals: the lexicographical basis is computed with the FGLM algorithm and split by
# Singular's `zero_decomp`. As in `primdec.lib`, the variables that appear linearly
# in the reduced basis (the elements with a linear leading term) are eliminated
# first and the elements are added to the components afterwards.
function _pd_zero_decomposition_lex_zero(I::MPolyIdeal; primary::Bool)
  R = base_ring(I)
  n = ngens(R)
  o = lex(R)
  G = collect(groebner_basis(I; ordering=o, algorithm=:fglm))
  lead(g) = exponent_vector(leading_monomial(g; ordering=o), 1)
  # a component with the generators of `G` is `I`, whose other bases are known; the
  # conversion by FGLM is expensive for a quotient of large dimension
  whole(gs) = length(gs) == length(G) && all(in(G), gs)
  fried = [g for g in G if sum(lead(g)) == 1]
  rest = [g for g in G if sum(lead(g)) > 1]
  fvars = [findfirst(==(1), lead(g)) for g in fried]
  # the elimination is only valid if the other elements do not contain these variables
  if isempty(fried) || !all(g -> all(((_, e),) -> all(i -> e[i] == 0, fvars), _pd_terms(g)), rest)
    comps = _pd_zero_decomp(R, G; primary)
    return map(comps) do (Q, P)
      JQ = whole(Q) ? I : _pd_with_bases(R, Q, o)
      return (JQ, Q == P ? JQ : whole(P) ? I : _pd_with_bases(R, P, o))
    end
  end
  isempty(rest) && return [(_pd_with_bases(R, fried, o), _pd_with_bases(R, fried, o))]
  keep = setdiff(1:n, fvars)
  S, _ = polynomial_ring(coefficient_ring(R), symbols(R)[keep]; cached=false)
  lexS = lex(S)
  function to_S(g, skip)
    ctx = MPolyBuildCtx(S)
    for (c, e) in _pd_terms(g)
      e == skip || push_term!(ctx, c, e[keep])
    end
    return finish(ctx)
  end
  function lift(g)
    ctx = MPolyBuildCtx(R)
    for (c, e) in _pd_terms(g)
      ee = zeros(Int, n)
      ee[keep] = e
      push_term!(ctx, c, ee)
    end
    return finish(ctx)
  end
  # the eliminated elements with the tails reduced by a component of the small ring
  function with_fried(Qs)
    JS = ideal(S, Qs)
    JS.gb[lexS] = IdealGens(S, Qs, lexS; isGB=true, isReduced=true)
    gens_R = elem_type(R)[lift(g) for g in Qs]
    for g in fried
      lt = leading_term(g; ordering=o)
      t = to_S(g, lead(g))
      is_zero(t) || (t = normal_form(t, JS; ordering=lexS))
      push!(gens_R, lt + lift(t))
    end
    return gens_R
  end
  comps = _pd_zero_decomp(S, [to_S(g, nothing) for g in rest]; primary)
  return map(comps) do (Q, P)
    gQ = with_fried(Q)
    gP = Q == P ? gQ : with_fried(P)
    JQ = whole(gQ) ? I : _pd_with_bases(R, gQ, o)
    return (JQ, gP === gQ ? JQ : whole(gP) ? I : _pd_with_bases(R, gP, o))
  end
end

# The zero-dimensional ideal generated by the reduced lexicographical Groebner basis
# `gs` for the ordering `o`, with this basis stored in the ideal and the degree
# reverse lexicographical Groebner basis computed from it with the FGLM algorithm.
# The generators of the lexicographical basis can have a high degree, which makes
# the computation of other bases from the generators expensive.
function _pd_with_bases(R::MPolyRing, gs::Vector, o::MonomialOrdering)
  J = ideal(R, gs)
  J.gb[o] = IdealGens(R, gs, o; isGB=true, isReduced=true)
  try
    fglm(J; start_ordering=o, destination_ordering=degrevlex(R))
  catch e
    e isa ErrorException || rethrow()
  end
  return J
end

# `_pd_zero_decomposition_lex_zero`, or `nothing` if Singular cannot work with the
# coefficient field or fails, in which case the native decomposition has to be used.
function _pd_try_zero_decomposition_lex_zero(I::MPolyIdeal; primary::Bool)
  _pd_singular_supported(coefficient_ring(base_ring(I))) || return nothing
  try
    comps = _pd_zero_decomposition_lex_zero(I; primary)
    return _pd_zero_components_complete(I, comps) ? comps : nothing
  catch e
    e isa ErrorException || rethrow()
    return nothing
  end
end

# The number of monomials that are not divisible by any of the exponent vectors
# `leads`, which is the dimension of the quotient by a zero-dimensional ideal if the
# vectors are the leading monomials of a Groebner basis.
function _pd_standard_count(leads::Vector{Vector{Int}}, k::Int=1)
  isempty(leads) && return typemax(Int)
  k > length(first(leads)) && return 0
  total = 0
  e = 0
  while true
    restricted = [l for l in leads if l[k] <= e]
    # a pure power of the variable `k` that divides `x_k^e` leaves no monomials
    any(l -> all(iszero, l[k+1:end]), restricted) && return total
    total += _pd_standard_count(restricted, k + 1)
    e += 1
  end
end

_pd_lex_leads(gs, o) = Vector{Int}[exponent_vector(leading_monomial(g; ordering=o), 1) for g in gs]

# Whether the components `(Q, P)` of the zero-dimensional ideal `I` have the vector
# space dimensions of `I` in total, which they have if no component is missing:
# `zero_decomp` can lose components (for `cyclic-6` over a finite field it returns
# 120 of the 156 points) and then the matrix based decomposition is used instead.
function _pd_zero_components_complete(I::MPolyIdeal, comps)
  o = lex(base_ring(I))
  count(J) = _pd_standard_count(_pd_lex_leads(groebner_basis(J; ordering=o), o))
  return sum(count(Q) for (Q, _) in comps) == count(I)
end

# The distinct non-unit leading coefficients (in `K[u]`) of the lexicographical
# basis `gx` of the extension, whose elements lie in `I`. Dividing an element of
# the extension by it only needs powers of these, so `I : h^oo` for their lcm `h`
# is the contraction of the extension, as for the leading coefficients of a
# Groebner basis in `K[x, u]`, but there are far fewer of them.
function _pd_lex_lead_coeffs(E::_PDExtension, gx::Vector)
  o = _pd_lex_ordering(E.R, E.X, E.U)
  cs = elem_type(E.R)[]
  for g in gx
    c = _pd_lead_coeff_in(_pd_from_ext(E, g), E.U, o)
    is_unit(c) || c in cs || push!(cs, c)
  end
  return cs
end

# The contraction `J K(u)[x'] ∩ K[x]` of an ideal of `K(u)[x']` given by a
# lexicographical Groebner basis `gs`: the saturation of the generators, made
# integral, by the leading coefficients of the basis, see `sat2` in `primdec.lib`.
function _pd_contract_lex(E::_PDExtension, gs::Vector)
  R = E.R
  L = ideal(R, [_pd_from_ext(E, g) for g in gs])
  o = _pd_lex_ordering(R, E.X, E.U)
  cs = elem_type(R)[]
  for g in gens(L)
    c = _pd_lead_coeff_in(g, E.U, o)
    is_unit(c) || c in cs || push!(cs, c)
  end
  return _pd_saturate(L, _pd_irreducible_factors(cs))
end
