Return the discriminant ``\Delta = 4 f^3 + 27 g^2`` of the Weierstrass model equivalent to the given global Tate model.

# Examples
```jldoctest
julia> using Random;

julia> t = global_tate_model_over_projective_space(2, rng = Random.Xoshiro(1234))
