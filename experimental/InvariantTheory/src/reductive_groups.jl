# Cached, as this elimination is the expensive step of Derksen's algorithm.
@attr MPolyIdeal{mpoly_type(FldT)} function proj_of_image_ideal(
  R::RedGroupInvarRing{FldT}
) where {FldT}
  return proj_of_image_ideal(representation(R))
end

# Hilbert's ideal in the ring K[x, y, zz] of proj_of_image_ideal, where the
# Reynolds operator is applied: by Derksen, it is obtained by setting y = 0.
@attr ideal_type(PolyRingT) function _null_cone_ideal_xyz(
  R::RedGroupInvarRing{FldT,PolyRingElemT,PolyRingT}
) where {FldT,PolyRingElemT,PolyRingT}
  b = proj_of_image_ideal(R)
  n = degree(representation(R))
  mixed_ring_xy = base_ring(b)
  xyz = gens(mixed_ring_xy)
  V = vcat(xyz[1:n], [zero(mixed_ring_xy) for _ in 1:n], xyz[(2 * n + 1):end])
  mixed_ring_graded, _ = grade(mixed_ring_xy)
  mapp = hom(mixed_ring_xy, mixed_ring_graded, gens(mixed_ring_graded))
  I = ideal(
    mixed_ring_graded, elem_type(mixed_ring_graded)[mapp(evaluate(f, V)) for f in gens(b)]
  )
  # the ring is passed as there are no generators if I is zero
  return ideal(mixed_ring_graded, minimal_generating_set(I))
end

@doc raw"""
    null_cone_ideal(RG::RedGroupInvarRing)

Return Hilbert's ideal, the ideal of `polynomial_ring(RG)` generated by the invariants
of positive degree.

Its zero set is the null cone, the set of all $v \in V$ such that the closure of the
orbit $G v$ contains $0$. The generators are computed as in Derksen's algorithm
[Der99](@cite) and need not be invariants.

# Examples
For binary quartics, the second generator is not invariant:
```jldoctest
julia> G = linearly_reductive_group(:SL, 2, QQ);

julia> RG = invariant_ring(representation_on_forms(G, 4));

julia> null_cone_ideal(RG)
Ideal generated by
  X[1]*X[5] - 4*X[2]*X[4] + 3*X[3]^2
  4*X[1]*X[3]*X[5] - 3*X[1]*X[4]^2 - 3*X[2]^2*X[5] + 2*X[2]*X[3]*X[4]
```
"""
@attr ideal_type(PolyRingT) function null_cone_ideal(
  R::RedGroupInvarRing{FldT,PolyRingElemT,PolyRingT}
) where {FldT,PolyRingElemT,PolyRingT}
  I = _null_cone_ideal_xyz(R)
  S = polynomial_ring(R)
  n = ngens(S)
  phi = hom(base_ring(I), S, vcat(gens(S), [zero(S) for _ in (n + 1):ngens(base_ring(I))]))
  return ideal(S, elem_type(S)[phi(f) for f in gens(I)])
end

polynomial_ring(R::RedOrTorGroupInvarRing) = R.poly_ring
group(R::RedOrTorGroupInvarRing) = R.group
representation(R::RedOrTorGroupInvarRing) = R.representation
coefficient_ring(R::RedOrTorGroupInvarRing) = R.field

@doc raw"""
    fundamental_invariants(RG::RedGroupInvarRing, algorithm::Symbol = :default)

Return a system of fundamental invariants for `RG`.

The result is cached, so calling this function again with argument `RG`
will be fast and give the same result.

# Implemented Algorithms

Both algorithms compute generators of Hilbert's null-cone ideal as in Derksen's algorithm
[Der99](@cite). Then
- `algorithm = :reynolds` applies the Reynolds operator to these generators. This needs a
  known Reynolds operator, that is, a group created from a symbol such as `:SL`.
- `algorithm = :linear_algebra` computes, by linear algebra, a basis of the invariants in
  each degree of a generator of the null-cone ideal, and keeps those which are not
  polynomials in invariants of smaller degree.

By default, the function uses `:reynolds` if a Reynolds operator is known, and
`:linear_algebra` otherwise (for groups given by their defining ideal).

# Examples
```jldoctest
julia> G = linearly_reductive_group(:SL, 2, QQ);

julia> r = representation_on_forms(G, 2);

julia> RG = invariant_ring(r);

julia> fundamental_invariants(RG)
1-element Vector{MPolyDecRingElem{QQFieldElem, QQMPolyRingElem}}:
 -X[1]*X[3] + X[2]^2

```
"""
function fundamental_invariants(z::RedGroupInvarRing, algorithm::Symbol=:default)
  if !isdefined(z, :fundamental)
    if algorithm === :default
      algorithm = _has_reynolds_operator(group(z)) ? :reynolds : :linear_algebra
    end
    @req algorithm in (:reynolds, :linear_algebra) "unsupported algorithm :$algorithm"
    @req algorithm === :linear_algebra || _has_reynolds_operator(group(z)) "no Reynolds operator is known for this group"

    if algorithm === :reynolds
      z.fundamental = inv_generators(z)
    else
      z.fundamental = inv_gens_no_reynolds(z)
    end
  end
  return copy(z.fundamental)
end

