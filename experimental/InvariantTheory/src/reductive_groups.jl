@doc raw"""
    representation_reductive_group(G::LinearlyReductiveGroup, M::MatElem)
    representation_reductive_group(G::LinearlyReductiveGroup)

Return the representation $\rho$ of `G` given by the square matrix `M`, whose entries
are polynomials in `base_ring(defining_ideal(G))`.

It is not checked that `M` defines a representation of `G`.

If `G` is $\text{SL}_m$, then `M` may be omitted, and the natural representation of `G`
