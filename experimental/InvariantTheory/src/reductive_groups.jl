function _direct_sum(
  X::RepresentationLinearlyReductiveGroup, Y::RepresentationLinearlyReductiveGroup
)
  @req group(X) === group(Y) "the representations must be of the same group"
  G = group(X)
  R = base_ring(defining_ideal(G))
  Mat = block_diagonal_matrix(
    R, [Matrix(representation_matrix(X)), Matrix(representation_matrix(Y))]
  )
  return RepresentationLinearlyReductiveGroup(G, Mat)
end

function _direct_sum(V::Vector{RepresentationLinearlyReductiveGroup})
  n = length(V)
  G = group(V[1])
  for i in 2:n
    @req G === group(V[i]) "the representations must be of the same group"
  end
  R = base_ring(defining_ideal(G))
  Mat = block_diagonal_matrix(R, [Matrix(representation_matrix(V[i])) for i in 1:n])
  return RepresentationLinearlyReductiveGroup(G, Mat)
end

function _tensor_product(
  X::RepresentationLinearlyReductiveGroup, Y::RepresentationLinearlyReductiveGroup
)
  @req group(X) === group(Y) "the representations must be of the same group"
  Mat = kronecker_product(representation_matrix(X), representation_matrix(Y))
  return RepresentationLinearlyReductiveGroup(group(X), Mat)
end

function _tensor_product(V::Vector{RepresentationLinearlyReductiveGroup})
  n = length(V)
  for i in 2:n
    @req group(V[1]) === group(V[i]) "the representations must be of the same group"
  end
  Mat = representation_matrix(V[1])
  for i in 2:n
    Mat = kronecker_product(Mat, representation_matrix(V[i]))
  end
  return RepresentationLinearlyReductiveGroup(group(V[1]), Mat)
end

# Compute the representation matrices of SL_m acting over m-forms of symmetric
# degree sym_deg
function _rep_mat(G::LinearlyReductiveGroup, sym_deg::Int)
  group_type(G) === :SL || error("Only implemented for SLm")
  m = group_dim(G)
  R = base_ring(defining_ideal(G))
  mixed_ring, t = polynomial_ring(R, :t => 1:m; cached=false)
  group_mat = natural_representation(G)
  new_vars = group_mat * t

  b = [
    multinomial_coefficient(sym_deg, first(AbstractAlgebra.exponent_vectors(a))) * a for
    a in monomials_of_degree(mixed_ring, sym_deg)
  ]
  n = length(b)

  # transform the b elements
  images_of_b = [evaluate(f, new_vars) for f in b]

  mat = zero_matrix(R, n, n)
  for j in 1:n
    f = images_of_b[j]
    x = mixed_ring()
    # express f as a linear combination of elements in b
    for i in 1:n
      c = coeff(f, leading_exponent(b[i]))
      mat[i, j] = c / leading_coefficient(b[i])
    end
  end
  return mat
end

function multinomial_coefficient(n::Int, v::AbstractVector{<:IntegerUnion})
  x = prod(factorial(ZZ(k)) for k in v)
  return divexact(factorial(ZZ(n)), x)
end

