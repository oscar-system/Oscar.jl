# This code uses Derksen's algorithm [Der99] to compute fundamental invariants
# of linearly reductive groups.
# We first set up a LinearlyReductiveGroup, then we set up a representation via
# which the group acts on a vector space (RepresentationLinearlyReductiveGroup).
# Then we set up the invariant ring of the group. The fundamental invariants are
# computed using Derksen's algorithm.
# As of now, the only Reynolds operator that is implemented is the one for SLm,
# using Cayley's Omega process.

################################################################################
#
#  Linearly reductive groups
#
################################################################################

# As of now, linearly reductive groups are only implemented for SLm, its direct
# products and tensors.

function Base.show(io::IO, ::MIME"text/plain", G::LinearlyReductiveGroup)
  io = pretty(io)
  if isdefined(G, :group)
    println(io, "Linearly reductive group ", group_type(G), group_dim(G))
    print(terse(io), Indent(), "defined over ", Lowercase(), base_ring(G))
    print(io, Dedent())
  else
    println(io, "Linearly reductive group defined by")
    print(io, Indent(), Lowercase(), defining_ideal(G))
    print(io, Dedent())
  end
end

function Base.show(io::IO, G::LinearlyReductiveGroup)
  if is_terse(io)
    print(io, "Linearly reductive group")
  else
    print(io, "Linearly reductive group")
    if isdefined(G, :group)
      print(io, " ", group_type(G), "(", group_dim(G), ",")
      print(terse(io), base_ring(G))
      print(io, ")")
    end
  end
end

@doc raw"""
    linearly_reductive_group(sym::Symbol, m::Int, k::Field)

Return the linearly reductive group indicated by `sym`, defined over the field `k`.

Currently, the supported options for `sym` are:
* `:SL`, corresponding to the special linear group $\text{SL}_m$.

For $m \geq 2$, $\text{SL}_m$ is not linearly reductive in positive characteristic,
so `k` must have characteristic 0.

# Examples
```jldoctest
julia> G = linearly_reductive_group(:SL, 2, QQ)
Linearly reductive group SL2
  defined over QQ

julia> defining_ideal(G)
Ideal generated by
  z[1, 1]*z[2, 2] - z[2, 1]*z[1, 2] - 1
```
"""
linearly_reductive_group(sym::Symbol, m::Int, k::Field) = LinearlyReductiveGroup(sym, m, k)

@doc raw"""
    linearly_reductive_group(sym::Symbol, m::Int, R::MPolyRing)

Return the linearly reductive group indicated by `sym`, with its defining ideal in `R`.
The group is defined over the coefficient field $k$ of `R`.

Currently, the supported options for `sym` are:
* `:SL`, corresponding to the special linear group $\text{SL}_m$. Its defining ideal is
  generated by $\det(Z) - 1$, where `R` has $m^2$ variables and $Z$ is the $m \times m$
  matrix filled with them column by column.

For $m \geq 2$, $\text{SL}_m$ is not linearly reductive in positive characteristic,
so $k$ must have characteristic 0.

# Examples
```jldoctest
julia> S, c = polynomial_ring(QQ, :c => (1:2, 1:2));

julia> G = linearly_reductive_group(:SL, 2, S)
Linearly reductive group SL2
  defined over QQ

julia> defining_ideal(G)
Ideal generated by
  c[1, 1]*c[2, 2] - c[2, 1]*c[1, 2] - 1
```
"""
linearly_reductive_group(sym::Symbol, m::Int, R::MPolyRing) =
  LinearlyReductiveGroup(sym, m, R)

@doc raw"""
    linearly_reductive_group(I::MPolyIdeal)

Return the linearly reductive group $G$ whose points are the zeros of `I`. The group
is defined over the coefficient field $k$ of `base_ring(I)`.

It is not checked that `I` defines a linearly reductive group. No Reynolds operator is
known for $G$, so [`fundamental_invariants(RG::RedGroupInvarRing, algorithm::Symbol = :default)`](@ref)
uses linear algebra instead.

# Examples
The torus $K^{\ast}$, as the hyperbola $z_1 z_2 = 1$:
```jldoctest
julia> S, z = polynomial_ring(QQ, :z => 1:2);

julia> G = linearly_reductive_group(ideal(S, [z[1]*z[2] - 1]))
Linearly reductive group defined by
  ideal (z[1]*z[2] - 1)
```
"""
linearly_reductive_group(I::MPolyIdeal) = LinearlyReductiveGroup(I)

base_ring(G::LinearlyReductiveGroup) = G.field
defining_ideal(G::LinearlyReductiveGroup) = G.defining_ideal
group_type(G::LinearlyReductiveGroup) = isdefined(G, :group) ? G.group[1] : nothing
group_dim(G::LinearlyReductiveGroup) = isdefined(G, :group) ? G.group[2] : nothing

function natural_representation(G::LinearlyReductiveGroup)
  @req isdefined(G, :natural_representation) "no natural representation is known for a group given by its defining ideal"
  return G.natural_representation
end

# Whether we know a Reynolds operator for G. This is the case for SLm (Cayley's
# Omega process), but not for a group given only by its defining ideal.
_has_reynolds_operator(G::LinearlyReductiveGroup) = group_type(G) === :SL

