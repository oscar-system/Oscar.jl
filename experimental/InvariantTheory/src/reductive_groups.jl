# Algorithm 4.5.1 in [DK15]
# Compute generators of the invariant ring RG without a Reynolds operator: the
# invariants of the degrees of the generators of the null cone ideal generate
# the invariant ring.
function inv_gens_no_reynolds(RG::RedGroupInvarRing)
  I = _null_cone_ideal_xyz(RG)
  b = proj_of_image_ideal(RG)
  ringg = polynomial_ring(RG)
  n = ngens(ringg)
  mixed_ring_xy = base_ring(b)
  phi = hom(
    mixed_ring_xy, ringg, vcat(gens(ringg), [0 for i in (n + 1):ngens(mixed_ring_xy)])
  )

  # An invariant of degree d is a polynomial in invariants of smaller degree if
  # and only if it lies in the ideal J generated by them: apply the Reynolds
  # operator, which exists although we do not know it, to a representation in J.
  # So we keep the invariants which are linearly independent modulo J.
  degrees = sort!(unique!(map(total_degree, gens(I))))
  ans_vect = Vector{elem_type(ringg)}()
  for d in degrees
    invs = map(phi, basis_no_reynolds(d, n, b))
    isempty(invs) && continue
    nfs = isempty(ans_vect) ? invs : normal_form(invs, ideal(ringg, ans_vect))
    B = BasisOfPolynomials(ringg)
    for (f, g) in zip(invs, nfs)
      add_to_basis!(B, g) && push!(ans_vect, f)
    end
  end
  return ans_vect
end

# Compute a K-basis of the invariants of degree d in the first n variables x of
# base_ring(b), a ring with variables x(1:n), y(1:n) and zz(1:?).
# A polynomial h in x is invariant if and only if h(x) - h(y) is in b.
function basis_no_reynolds(d::Int, n::Int, b::MPolyIdeal)
  mixed_ring = base_ring(b)
  xyz = gens(mixed_ring)
  x_to_y = hom(mixed_ring, mixed_ring, vcat(xyz[(n + 1):(2 * n)], xyz[(n + 1):end]))

  H = collect(monomials_of_degree(mixed_ring, d, 1:n))
  polys = normal_form([m - x_to_y(m) for m in H], b)

  #finding the generators of the kernel space
  V, VtoPoly = vector_space(base_ring(mixed_ring), polys)
  W = vector_space(base_ring(mixed_ring), length(polys))
  h = hom(W, V, [Oscar.preimage(VtoPoly, f) for f in polys])
  K, KtoW = kernel(h)
  alpha = KtoW.(gens(K))
  ans = Vector{elem_type(mixed_ring)}()
  for i in 1:length(alpha)
    pol = mixed_ring()
    for j in 1:length(alpha[i].v)
      pol += alpha[i][j] * H[j]
    end
    push!(ans, pol)
  end
  return ans
end
