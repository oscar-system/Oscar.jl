# Examples
The torus $K^{\ast}$ acting with weights $1$ and $-1$:
```jldoctest
julia> S, z = polynomial_ring(QQ, :z => 1:2);

julia> G = linearly_reductive_group(ideal(S, [z[1]*z[2] - 1]));

julia> r = representation_reductive_group(G, diagonal_matrix(S, [z[1], z[2]]))
Representation
  of linearly reductive group
  with representation matrix
  [z[1] 0; 0 z[2]]

julia> fundamental_invariants(invariant_ring(r))
1-element Vector{MPolyDecRingElem{QQFieldElem, QQMPolyRingElem}}:
 X[1]*X[2]
```
"""
representation_reductive_group(G::LinearlyReductiveGroup, M::MatElem) =
  RepresentationLinearlyReductiveGroup(G, M)
group(R::RepresentationLinearlyReductiveGroup) = R.group
representation_matrix(R::RepresentationLinearlyReductiveGroup) = R.rep_mat
vector_space_dim(R::RepresentationLinearlyReductiveGroup) = ncols(R.rep_mat)
degree(R::RepresentationLinearlyReductiveGroup) = vector_space_dim(R)

@doc raw"""
    representation_on_forms(G::LinearlyReductiveGroup, d::Int)

This is currently only implemented for special linear groups.

If $G$ is $\text{SL}_m$, return the representation obtained by letting $G$ act by linear
substitution on $m$-ary forms of degree $d$.

!!! note
    In accordance with classical papers, an $m$-ary form of degree $d$ is written as a linear combination
    of the basis with elements $\binom{d}{I}x^I$. Here, $I = (i_1, \dots, i_m)\in\mathbb Z_{\geq 0}^m$ with $i_1+\dots +i_m =d$.
    If $Z \in \text{SL}_m$, then the representation matrix, evaluated at $Z$, maps the coefficient
    vector of a form $f$ with respect to this basis to that of $f(Zx)$.

# Examples
```jldoctest
julia> G = linearly_reductive_group(:SL, 2, QQ);

julia> r = representation_on_forms(G, 2)
Representation
  of linearly reductive group SL(2,QQ)
  on symmetric forms of degree 2

julia> representation_matrix(r)
[      z[1, 1]^2                   2*z[1, 1]*z[2, 1]         z[2, 1]^2]
[z[1, 1]*z[1, 2]   z[1, 1]*z[2, 2] + z[2, 1]*z[1, 2]   z[2, 1]*z[2, 2]]
[      z[1, 2]^2                   2*z[1, 2]*z[2, 2]         z[2, 2]^2]
```
"""
function representation_on_forms(G::LinearlyReductiveGroup, d::Int)
  @req group_type(G) === :SL "Only implemented for SLm"
  return RepresentationLinearlyReductiveGroup(G, d)
end

function representation_reductive_group(G::LinearlyReductiveGroup)
  @req group_type(G) === :SL "Only implemented for SLm"
  M = natural_representation(G)
  return RepresentationLinearlyReductiveGroup(G, M)
end

