@doc raw"""
    determinantal_ideal(X::DeterminantalGerm) -> MPolyLocalizedIdeal

Return the determinantal ideal `I` defining the determinantal germ `X` in the ring of the ambient germ of `X`.
!!! warning
    The generators of the `determinantal_ideal` might differ from the generators of the `defining_ideal`, if the determinantal structure was later endowed onto an existing scheme.

!!! note
    The returned determinantal ideal `I` is not an ideal of a polynomial ring, but an ideal of a localization of a polynomial ring at the complement of a prime ideal. (Hence each generator of `I` has a numerator and a denominator.)

# Examples:
```jldoctest
julia> R, (x,y,z) = QQ[:x, :y, :z];

julia> L, _ = localization(R, complement_of_point_ideal(R, [0,0,0]));

julia> Q, _ = quo(L, ideal(L, [x*y, x*z, y*z]));

julia> X = spec(Q);

julia> A = L[x 0 z;  0 y z]
[x   0   z]
[0   y   z]

julia> X_A = DeterminantalGerm(X, A, 2)
Spectrum
  of localization
    of quotient
      of multivariate polynomial ring in 3 variables x, y, z
        over rational field
      by ideal (x*y, x*z, y*z)
    at complement of maximal ideal of point (0, 0, 0)

julia> determinantal_ideal(X_A)
Ideal generated by
  x*y
  x*z
  -y*z

julia> defining_ideal(X_A)
Ideal generated by
  x*y
  x*z
  y*z

julia> determinantal_ideal(X_A) == defining_ideal(X_A)
true

julia> R == base_ring(determinantal_ideal(X_A))
false

julia> L == base_ring(determinantal_ideal(X_A))
true
```
"""
@attr MPolyLocalizedIdeal function determinantal_ideal(X::DeterminantalGerm)
  _, _, t = determinantal_type(X) 
  return _determinantal_ideal(defining_matrix(X), t, _mat_type(X))
end



@doc raw"""
    defining_matrix(X::DeterminantalGerm) -> MatElem

Return the defining matrix `A` of the derterminantal germ `X` over the ring of the ambient germ of `X`.
!!! note
    The returned matrix `A` is not a matrix over a polynomial ring, but a matrix over a localization of a polynomial ring at the complement of a prime ideal. (Hence each entry of `A` has a numerator and a denominator.)

# Examples:
```jldoctest
julia> R, (x,y,z) = QQ[:x, :y, :z];

julia> A = R[x 0 z;  0 y z]
[x   0   z]
[0   y   z]

julia> X_A = DeterminantalGerm(A, 2, [0,0,0])
Spectrum
  of localization
    of quotient
      of multivariate polynomial ring in 3 variables x, y, z
        over rational field
      by ideal (x*y, x*z, -y*z)
    at complement of maximal ideal of point (0, 0, 0)

julia> defining_matrix(X_A)
[x   0   z]
[0   y   z]

julia> base_ring(A) == base_ring(defining_matrix(X_A))
false

julia> base_ring(A)
Multivariate polynomial ring in 3 variables x, y, z
  over rational field

julia> base_ring(defining_matrix(X_A))
Localization
  of multivariate polynomial ring in 3 variables x, y, z
    over rational field
  at complement of maximal ideal of point (0, 0, 0)
```
"""
defining_matrix(X::DeterminantalGerm) = X.A



@doc raw"""
    determinantal_type(X::DeterminantalGerm) -> Int, Int, Int

Return the determinantal type `(n, m, t)` of the derterminantal germ `X`.
!!! note
    `X` is defined by the $t$-`minors` respectively the $2t$-`pfaffians` (in the `skew-symmetric` case) of the defining matrix of size `n x m`.

# Examples:
```jldoctest
julia> R, (x,y) = QQ[:x, :y];

julia> A = R[x y 0;  0 x^3 y]
[x     y   0]
[0   x^3   y]

julia> X_A = DeterminantalGerm(A, 2, [0,0])
Spectrum
  of localization
    of quotient
      of multivariate polynomial ring in 2 variables x, y
        over rational field
      by ideal (x^4, x*y, y^2)
    at complement of maximal ideal of point (0, 0)

julia> n, m, t = determinantal_type(X_A)
(2, 3, 2)

julia> minors(A, t)
3-element Vector{QQMPolyRingElem}:
 x^4
 x*y
 y^2



julia> B = R[0 0 x 0;  0 0 0 x*y+y^3;  -x 0 0 0; 0 -x*y-y^3 0 0] 
[ 0            0   x           0]
[ 0            0   0   x*y + y^3]
[-x            0   0           0]
[ 0   -x*y - y^3   0           0]

julia> X_B_skew = DeterminantalGerm(B, 2, [0,0], mat_type = :skew_symmetric)
Spectrum
  of localization
    of quotient
      of multivariate polynomial ring in 2 variables x, y
        over rational field
      by ideal (-x^2*y - x*y^3)
    at complement of maximal ideal of point (0, 0)

julia> n, m, t = determinantal_type(X_B_skew)
(4, 4, 2)

julia> pfaffians(B, 2t)
1-element Vector{QQMPolyRingElem}:
 -x^2*y - x*y^3
```
"""
function determinantal_type(X::DeterminantalGerm)
  n, m = size(X.A)
  return n, m, X.t
end



@doc raw"""
    _mat_type(X::DeterminantalGerm{<:Ring, <:Ring, <:AffineScheme, T}) where {T<:Val} -> T

Return the type of the `Val` `T` representing the matrix symmetry type of the determinantal germ `X`, i.e. this function either returns `Val{:generic}`, `Val{:symmetric}` or `Val{:skew_symmetric}`.

!!! note
    This command is not exported and is only provided for convenience in programming.

# Examples:
julia> R, (x,y) = QQ[:x, :y];

julia> A = R[x 0;  0 y^2+x^2]
[x           0]
[0   x^2 + y^2]

julia> X_A = DeterminantalGerm(A, 2, [0,0]);

julia> X_A_sym = DeterminantalGerm(A, 2, [0,0], mat_type = :symmetric);

julia> Oscar._mat_type(X_A)
Val{:generic}

julia> Oscar._mat_type(X_A_sym)
Val{:symmetric}
"""
_mat_type(X::DeterminantalGerm{<:Ring, <:Ring, <:AffineScheme, T}) where {T<:Val} = T
