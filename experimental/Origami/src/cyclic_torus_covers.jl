@doc raw"""
    translation_group_on_homology_of_tn(n::Int)

Returns: the group of translations (as matrices) acting on monodromy vectors with respect to ``L``. 

This group of order ``n^2`` is generated by the matrices representing the translation by one square to the right and the translation by one square up with respect to the basis ``L``.

```jldoctest
julia> G = translation_group_on_homology_of_tn(3)
Matrix group of degree 10
  over integer ring

julia> order(G)
9
```
"""
function translation_group_on_homology_of_tn(n::Int)
  gens_gap = GAP.Globals.GeneratorsOfGroup(GAP.Globals.TranslationGroupOnHomologyOfTn(n))
  gens_oscar = [matrix(ZZ, g) for g in gens_gap]
  return matrix_group(gens_oscar)
end

