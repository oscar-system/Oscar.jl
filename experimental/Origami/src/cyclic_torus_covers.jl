@doc raw"""
    action_of_matrix_on_homology_of_tn(n::Int, A::Matrix)

Returns: a matrix representing the action of ``A \in {\rm SL}_2(\mathbb{Z})`` on the homology of ``T_n`` with respect to ``L``.

Any matrix ``A \in {\rm SL}_2(\mathbb{Z})`` can be viewed as an affine map on ``T_n`` if we assume that the lower left corner is
fixed. ``A`` must be in ``{\rm SL}_2(\mathbb{Z})``. It is written as a word in the generators ``S`` and ``T`` of
