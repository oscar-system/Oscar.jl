@doc raw"""
    stratum(o::Origami)

This function calculates the stratum of an origami, i.e. the list of the (non-ascendingly
ordered) non-zero degrees of the singularities. For a singularity of cone angle ``2 k \pi`` the
degree of the singularity is ``k - 1``.

# Examples
```jldoctest
julia> o = origami(cperm([1,2],[3,4]), cperm([2,5,3,6],[4,7]))
Origami ((1,2)(3,4),(2,5,3,6)(4,7), 7)

julia> stratum(o)
3-element Vector{Int64}:
 2
 1
 1
```
"""
function stratum(o::Origami)
  h = horizontal_perm(o)
  v = vertical_perm(o)
  commutator = comm(h, v)
  cycs = cycles(commutator)
  unsorted_stratum = [length(c) - 1 for c in cycs if length(c) > 1]
  return sort!(unsorted_stratum; rev=true)
end

@doc raw"""
    genus(o::Origami)

Calculates the genus of an origami.

# Examples
```jldoctest
julia> o = origami(cperm([1,2]), cperm([2,3]))
Origami ((1,2),(2,3), 3)

julia> genus(o)
2
```
"""
function genus(o::Origami)
  # the stratum degrees sum to 2g-2, so the division is exact
  return ZZ(div(sum(stratum(o)) + 2, 2))
end

function veech_group(o::Origami)
  o = normal_form(o)

  index_of = Dict{typeof(canonical_origami_key(o)), Int}()
  index_of[canonical_origami_key(o)] = 1

  orbit = Origami[o]
  queue = Int[1]
  s_imgs = Int[]
  t_imgs = Int[]

  while !isempty(queue)
    i = popfirst!(queue)
    P = orbit[i]

    for (j, Q0) in enumerate((action_s(P), action_t(P)))
      Q = normal_form(Q0)
      key = canonical_origami_key(Q)
      k = get!(index_of, key, length(orbit) + 1)
      if k > length(orbit)
        push!(orbit, Q)
        push!(queue, k)
      end
      imgs = j == 1 ? s_imgs : t_imgs
      resize!(imgs, max(length(imgs), i))
      imgs[i] = k
    end
  end

  n = length(orbit)
  G = symmetric_group(n)
  # GAP returns ModularSubgroup(PermList(sigma_S)^-1, PermList(sigma_T)^-1)
  return modular_subgroup_via_left_action(G(s_imgs), G(t_imgs))
end

@doc raw"""
    index_monodromy_group(o::Origami)

Calculates the index of the monodromy group of the origami `o`, i.e. the index of the subgroup
generated by `h` and `v` in the symmetric group in ``d`` letters, where ``d`` is the degree of `o`.

# Examples
```jldoctest
julia> o = origami(cperm([1,3,6],[4,5]), cperm([2,4,3,5],[7,1]))
Origami ((1,3,6)(4,5),(1,7)(2,4,3,5), 7)

julia> index_monodromy_group(o)
1
```
"""
function index_monodromy_group(o::Origami)
  return index(perm_group(o), permutation_group(degree(o), [horizontal_perm(o), vertical_perm(o)]))
end

