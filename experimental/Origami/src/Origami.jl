@doc raw"""
    translations(o::Origami)

Computes all translations of the origami `o` as permutations of the squares of `o`. This is equivalent
to the permutations ``t`` which satisfy ``h^t = h`` and ``v^t = v``.
# Examples
```jldoctest
julia> o = origami(cperm([1,2,3,4]), cperm([1,2],[3,4]))
Origami ((1,2,3,4),(1,2)(3,4), 4)

julia> translations(o)
2-element Vector{PermGroupElem}:
 ()
 (1,3)(2,4)
```
"""
function translations(o::Origami)
  h = horizontal_perm(o)
  v = vertical_perm(o)

  function act_on_tuples_by_conj(tup::Vector{PermGroupElem}, g::PermGroupElem)
    return [tup[1]^g, tup[2]^g]
  end

  S = stabilizer(perm_group(o), [h, v], act_on_tuples_by_conj)[1]
  return elements(S)
end

@doc raw"""
    is_hyperelliptic(o::Origami)

Tests whether an origami is hyperelliptic.
# Examples
```jldoctest
julia> o = origami(cperm([1,2,3,4]), cperm([1,2],[3,4]))
Origami ((1,2,3,4),(1,2)(3,4), 4)

julia> is_hyperelliptic(o)
true

julia> o = origami(cperm([1,2,3,4,5,6]), cperm([1,2],[3,4],[5,6]))
Origami ((1,2,3,4,5,6),(1,2)(3,4)(5,6), 6)

julia> is_hyperelliptic(o)
false
```
"""
function is_hyperelliptic(o::Origami)
  # TODO elaborate on what hyperelliptic means for origamis?
  # check whether -1 is in the veech group
  if !veech_group_is_even(o)
    return false
  end

  x = horizontal_perm(o)
  y = vertical_perm(o)
  g = genus(o)

  L = point_reflections(o)
  L = filter(i -> order(i) == 2, L)

  isempty(L) && return false

  degree_list = collect(1:degree(o))
  for sigma in L
    # fixpoints
    b =
      number_of_fixed_points(sigma) +
      number_of_fixed_points(sigma * x) +
      number_of_fixed_points(sigma * y)

    p1 = sigma * x^-1 * y^-1
    p2 = y * x * (x * y)^-1
    for i in degree_list
      if i^p1 == i^p2
        b += 1
      end
    end

    if 2 * g + 2 - b == 0
      return true
    end
  end

  return false
end

@doc raw"""
    cylinder_structure(o::Origami)
Returns a list of integer tuples, where each tuple `(h, w)` corresponds to a cylinder of `o` of height
`h` and width `w`.
# Examples
```jldoctest
julia> o = origami(cperm([1,2],[3,4]), cperm([1,3,5,6],[2,4]))
Origami ((1,2)(3,4),(1,3,5,6)(2,4), 6)

julia> cylinder_structure(o)
2-element Vector{Tuple{Int64, Int64}}:
 (2, 2)
 (2, 1)
```
"""
function cylinder_structure(o::Origami)
  gap_obj = GAP.Globals.CylinderStructure(GapObj(o))
  cyl_tuples = Vector{Tuple{Int,Int}}(gap_obj)::Vector{Tuple{Int,Int}}
  return cyl_tuples
end

function veech_group_and_orbit(o::Origami)
  o = normal_form(o)

  index_of = Dict{typeof(canonical_origami_key(o)), Int}()
  index_of[canonical_origami_key(o)] = 1

  orbit = Origami[o]
  matrices = ZZMatrix[identity_matrix(ZZ, 2)]
  queue = Int[1]
  s_imgs = Int[]
  t_imgs = Int[]

  matS = matrix(ZZ, [0 -1; 1 0])
  matT = matrix(ZZ, [1 1; 0 1])

  while !isempty(queue)
    i = popfirst!(queue)
    P = orbit[i]
    # left action: the matrix of a child is gen * matrix of the parent
    gens = ((action_s(P), matS), (action_t(P), matT))

    for (j, (Q0, gen)) in enumerate(gens)
      Q = normal_form(Q0)
      key = canonical_origami_key(Q)
      k = get(index_of, key, 0)
      if k == 0
        k = length(orbit) + 1
        index_of[key] = k
        push!(orbit, Q)
        push!(matrices, gen * matrices[i])
        push!(queue, k)
      end
      imgs = j == 1 ? s_imgs : t_imgs
      resize!(imgs, max(length(imgs), i))
      imgs[i] = k
    end
  end

  n = length(orbit)
  G = symmetric_group(n)
  group = modular_subgroup_via_left_action(G(s_imgs), G(t_imgs))
  #TODO maybe there's a better structure to return?
  return (veech_group = group, orbit = orbit, matrices = matrices)
end

function veech_group_is_even(o::Origami)
  q = action_s(action_s(o))
	return are_equivalent(o, q)
end

@doc raw"""
    are_equivalent(o1::Origami, o2::Origami)
Checks whether two given origamis are equivalent, i.e. whether the permutations describing them are
simultaneously conjugated.
# Examples
```jldoctest
julia> o1 = origami(cperm([1,2,3,4]), cperm([3,4]))
Origami ((1,2,3,4),(3,4), 4)

julia> o2 = origami(cperm([1,3,2,4]), cperm([2,3]))
Origami ((1,3,2,4),(2,3), 4)

julia> are_equivalent(o1, o2)
true
```
"""
function are_equivalent(o1::Origami, o2::Origami)
  return canonical_origami_key(o1) == canonical_origami_key(o2)
end

@doc raw"""
    point_reflections(o::Origami)

Computes all point reflections of the origami `o` as permutations of the squares of `o`. A point
reflection is an affine homeomorphism with derivative ``-I``, where ``I`` is the identity matrix. This is
equivalent to the permutations ``t`` which satisfy ``h^t = h^{-1}`` and ``v^t = v^{-1}``.
# Examples
```jldoctest
julia> o = origami(cperm([1,2,3,4]), cperm([1,2],[3,4]))
Origami ((1,2,3,4),(1,2)(3,4), 4)

julia> point_reflections(o)
2-element Vector{PermGroupElem}:
 (1,2)(3,4)
 (1,4)(2,3)
```
"""
function point_reflections(o::Origami)
  # TODO do we really want an exception here, or maybe just return an empty list?
  @req veech_group_is_even(o) "Veech group must contain -1"

  h = horizontal_perm(o)
  v = vertical_perm(o)
  o1 = origami(h^-1, v^-1)
  h1 = horizontal_perm(o1)
  v1 = vertical_perm(o1)
  G = normalform_conjugators(o)
  G1 = normalform_conjugators(o1)

  f(i) = origami(h^i, v^i)
  f1(i) = origami(h1^i, v1^i)

  # origamis derived from the permutations above
  O = f.(G)
  # we need to calculate these to test find k s.t.
  # sigma_i *origami *sigma_i^-1=delta_k(i)*origami_1*delta_k(i)^-1
  O1 = f1.(G1)

  # fitting the permutations together
  result = PermGroupElem[]

  l = length(O)
  for i in 1:l
    index = findfirst(item -> item == O[i], O1)
    push!(result, G[i] * (G1[index])^-1)
  end

  return unique!(result)
end

function automorphism_list(o::Origami)
  return vcat(translations(o), point_reflections(o))
end
