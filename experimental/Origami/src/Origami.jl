```
"""
function vertical_perm(o::Origami)
  return o.v
end

@doc raw"""
    degree(o::Origami)

Returns the degree of the origami, i.e. the number of unit squares which are glued together. In
terms of permutations, the degree corresponds to the largest moved points of `h` and `v`.

# Examples
```jldoctest
julia> o = origami(cperm([1,2]), cperm([2,3]))
Origami ((1,2),(2,3), 3)

julia> degree(o)
3
```
"""
function degree(o::Origami)
  return o.d
end

@doc raw"""
    perm_group(o::Origami)

Returns the underlying permutation group that the origami permutations live in, i.e. the symmetric
group in ``d`` letters, where ``d`` is the degree of the origami.

# Examples
```jldoctest
julia> o = origami(cperm([1,2]), cperm([2,3]))
Origami ((1,2),(2,3), 3)

julia> perm_group(o)
Symmetric group of degree 3
```
"""
function perm_group(o::Origami)
  return symmetric_group(o.d)
end

function Base.show(io::IO, o::Origami)
  h = horizontal_perm(o)
  v = vertical_perm(o)
  d = degree(o)
  print(io, "Origami ($(h),$(v), $(d))")
end

