@doc raw"""
    origami(h::PermGroupElem, v::PermGroupElem; check=true)

This function constructs an Origami object from two given permutations `h` and `v` . For
`check = true`, a test is performed to check whether the surface described by the given
permutations is connected, i.e. whether the group generated by the two permutations acts
transitively.

# Examples
```jldoctest
julia> h = @perm (1,2)
(1,2)

julia> v = @perm (2,3)
(2,3)

julia> o = origami(h,v)
Origami ((1,2),(2,3), 3)
```
"""
function origami(h::PermGroupElem, v::PermGroupElem; check=true)
  d = max(largest_moved_point(h), largest_moved_point(v))
  G = symmetric_group(d)
  if check
    obj = GAP.Globals.Origami(GapObj(h), GapObj(v))
  else
    obj = GAP.Globals.OrigamiNC(GapObj(h), GapObj(v), d)
  end
  return Origami(obj, G(h), G(v), d)
end

# ugly workaround
function from_GAP_origami(o::GapObj)
  d = GAP.Globals.DegreeOrigami(o)::Int
  G = symmetric_group(d)
  h = PermGroupElem(G, GAP.Globals.HorizontalPerm(o))
  v = PermGroupElem(G, GAP.Globals.VerticalPerm(o))
  return origami(h, v)
end

function Base.:(==)(a::Origami, b::Origami)
  # TODO rewrite this? for now use Gap equality
  # the degree must be compared as well, so that `==` stays consistent with `hash`
  return (a.h == b.h) && (a.v == b.v) && (a.d == b.d)
end

function Base.hash(o::Origami, h::UInt)
  return hash(o.h, hash(o.v, hash(o.d, h)))
end

@doc raw"""
    horizontal_perm(o::Origami)

Returns the permutation `h` describing the horizontal gluing of the unit squares.

# Examples
```jldoctest
julia> o = origami(cperm([1,2]), cperm([2,3]))
Origami ((1,2),(2,3), 3)

julia> horizontal_perm(o)
(1,2)
```
"""
function horizontal_perm(o::Origami)
  return o.h
end

@doc raw"""
    vertical_perm(o::Origami)

Returns the permutation `v` describing the vertical gluing of the unit squares.

# Examples
```jldoctest
julia> o = origami(cperm([1,2]), cperm([2,3]))
Origami ((1,2),(2,3), 3)

julia> vertical_perm(o)
