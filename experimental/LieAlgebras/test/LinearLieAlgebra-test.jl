    struct_const_L[6, :] = Vector{Tuple{QQFieldElem,Int64}}[
      [], [(QQ(-1), 3)], [(QQ(1), 2)], [(QQ(-1), 5)], [(QQ(1), 4)], []
    ]
    @test lie_algebra_struct_const(L) == struct_const_L

    L = special_orthogonal_lie_algebra(QQ, 5, identity_matrix(QQ, 5))
