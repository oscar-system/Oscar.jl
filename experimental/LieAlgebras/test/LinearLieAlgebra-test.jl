@testset "LieAlgebras.LinearLieAlgebra" begin
  @testset "constructors for R=$R, n=$n" for R in [QQ, cyclotomic_field(4)[1]], n in 1:6
    L = general_linear_lie_algebra(R, n)
    @test dim(L) == n^2

    L = special_linear_lie_algebra(R, n)
    @test dim(L) == n^2 - 1

    L = special_orthogonal_lie_algebra(R, n)
    @test dim(L) == div(n^2 - n, 2)

    if is_even(n)
      L = symplectic_lie_algebra(R, n)
      @test dim(L) == div(n^2 + n, 2)
    end
  end

  @testset "constructor checks" begin
    # `check=true` rejects linearly dependent and non-closed matrix bases
    e = matrix(QQ, [0 1; 0 0])
    f = matrix(QQ, [0 0; 1 0])
    @test_throws ArgumentError lie_algebra(QQ, 2, [e, 2 * e], [:e, :e2]; is_basis=true)
    @test_throws ArgumentError lie_algebra(QQ, 2, [e, f], [:e, :f]; is_basis=true)
    @test lie_algebra(QQ, 2, [e, f], [:e, :f]; is_basis=true, check=false) isa
      LinearLieAlgebra
    @test dim(lie_algebra(QQ, 2, [e, f, e * f - f * e], [:e, :f, :h]; is_basis=true)) == 3
  end

  @testset "lie_algebra(gens::Vector{<:MatElem})" begin
    # Lie algebra generated by matrices is the smallest subalgebra of gl_n containing them
    e = matrix(QQ, [0 1 0; 0 0 1; 0 0 0])
    f = matrix(QQ, [0 0 0; 2 0 0; 0 2 0])
    L = lie_algebra([e, f])
    @test L isa LinearLieAlgebra{QQFieldElem}
    @test dim(L) == 3
    lie_algebra_conformance_test(
      L, LinearLieAlgebra{QQFieldElem}, LinearLieAlgebraElem{QQFieldElem}
    )
    for g in [e, f, e * f - f * e]
      @test matrix_repr(L(g)) == g
    end
    @test_throws ArgumentError L(e * e)

    F = GF(3)
    L = lie_algebra([matrix(F, [0 1; 0 0]), matrix(F, [0 0; 1 0])])
    @test L isa LinearLieAlgebra{elem_type(F)}
    @test dim(L) == 3

    L = lie_algebra([zero_matrix(QQ, 2, 2)])
    @test dim(L) == 0

    @test_throws ArgumentError lie_algebra(QQMatrix[])
    @test_throws ArgumentError lie_algebra([identity_matrix(QQ, 2), identity_matrix(QQ, 3)])
    @test_throws ArgumentError lie_algebra([zero_matrix(QQ, 2, 3)])

    # names are given as a vector or as a prefix
    @test symbols(lie_algebra([e, f], :y)) == [:y_1, :y_2, :y_3]
    @test symbols(lie_algebra([e, f], [:a, :b, :c])) == [:a, :b, :c]
    @test_throws ArgumentError lie_algebra([e, f], [:a, :b])

    # with `is_basis=true`, the matrices are kept as basis
    h = e * f - f * e
    L = lie_algebra(QQ, 3, [e, f, h], [:e, :f, :h]; is_basis=true)
    @test matrix_repr_basis(L) == [e, f, h]
    @test_throws ArgumentError lie_algebra(QQ, 3, [e, f], [:e, :f]; is_basis=true)

    # with a given field, the entries are mapped into it
    e = matrix(ZZ, [0 1 0; 0 0 1; 0 0 0])
    f = matrix(ZZ, [0 0 0; 2 0 0; 0 2 0])
    L = @inferred lie_algebra(QQ, [e, f])
    @test matrix_repr_basis(L) ==
      matrix_repr_basis(lie_algebra(map_entries.(Ref(QQ), [e, f])))
    @test dim(@inferred lie_algebra(GF(2), [e, f])) == 1
    @test_throws ArgumentError lie_algebra(QQ, ZZMatrix[])
  end

  @testset "construction from matrices" begin
    L = special_linear_lie_algebra(QQ, 3)
    # `L(mat)` inverts `matrix_repr`
    for _ in 1:10
      x = LieAlgebraElem(L, rand(-10:10, dim(L)))
      @test x == @inferred L(matrix_repr(x))
      @test x == @inferred L(matrix_repr(x); check=false)
    end
    # matrices of wrong size or over a different field are rejected
    @test_throws ArgumentError L(zero_matrix(QQ, 2, 2))
    K1, _ = cyclotomic_field(4)
    K2, _ = cyclotomic_field(5)
    @test_throws ArgumentError special_linear_lie_algebra(K1, 3)(identity_matrix(K2, 3))
    # matrices outside of `L` are rejected, unless the check is disabled
    @test_throws ArgumentError L(identity_matrix(QQ, 3))
    @test matrix_repr(L(identity_matrix(QQ, 3); check=false)) != identity_matrix(QQ, 3)
  end

  @testset "membership of matrices" begin
    L = special_linear_lie_algebra(QQ, 3)
    # matrix representations of elements of `L` lie in `L`
    for _ in 1:10
      x = LieAlgebraElem(L, rand(-10:10, dim(L)))
      @test matrix_repr(x) in L
    end
    # other matrices do not
    @test !(identity_matrix(QQ, 3) in L)
    # matrices of wrong size or over a different field are rejected
    @test_throws ArgumentError zero_matrix(QQ, 2, 2) in L
    K1, _ = cyclotomic_field(4)
    K2, _ = cyclotomic_field(5)
    @test_throws ArgumentError identity_matrix(K2, 3) in special_linear_lie_algebra(K1, 3)
  end

  @testset "lie_algebra from elements" begin
    L = special_linear_lie_algebra(QQ, 3)
    e12, e13, e23 = basis(L)[1:3]

    # by default (`is_basis=false`), the result is the subalgebra generated by the elements
    LS = lie_algebra(L, [e12, e23])
    @test LS isa LinearLieAlgebra{QQFieldElem}
    @test dim(LS) == 3
    @test dim(lie_algebra([e12, e23])) == 3

    # with `is_basis=true`, they are kept as basis
    LS = lie_algebra(L, [e12, e13]; is_basis=true)
    @test matrix_repr_basis(LS) == matrix_repr.([e12, e13])
    @test_throws ArgumentError lie_algebra(L, [e12, e23]; is_basis=true)
    @test_throws ArgumentError lie_algebra(L, [e12, 2 * e12]; is_basis=true)
  end

