
@attributes mutable struct AffineSemigroup{T} # affine semigroup
  generators::MatElem{T}

  function AffineSemigroup(generators::MatElem{T}) where T <: ZZRingElem
    return new{T}(generators)
  end
end

function Base.show(io::IO, S::AffineSemigroup)
  print(io, "Affine semigroup in ambient dimension ", ambient_dimension(S))
end

function Base.show(io::IO, ::MIME"text/plain", S::AffineSemigroup)
  println(io, "Affine semigroup in ambient dimension ", ambient_dimension(S), " generated by")
  print(io, "  ", join(string.(gens(S)), "\n  "))
end

function gens(Q::AffineSemigroup)
  return [Q.generators[:, i] for i in 1:size(Q.generators, 2)]
end

function rank(Q::AffineSemigroup)
  return rank(matrix(ZZ,Q.generators))
end

# dimension d of the lattice ZZ^d containing Q
function ambient_dimension(Q::AffineSemigroup)
  return size(Q.generators, 1)
end

@doc raw"""
    affine_semigroup(M::Matrix{Int})
    affine_semigroup(V::Vector{Vector{Int}})

Create the affine semigroup generated by the columns of the integer matrix `M`,
respectively by the integer vectors in `V`.
"""
function affine_semigroup(M::MatElem{T}) where T
  return AffineSemigroup(map_entries(ZZ, M))
end

function affine_semigroup(M::MatElem{T}) where {T <: ZZRingElem}
  return AffineSemigroup(M)
end


function affine_semigroup(V_Q::Vector{Vector{Int}})
  @assert !is_empty(V_Q) "list of generators must not be empty"
  m = length(V_Q)
  n = length(first(V_Q))
  @assert all(length(v) == n for v in V_Q) "all vectors must have the same length"
  return affine_semigroup(matrix_space(ZZ, m, n)(reduce(vcat, V_Q)))
end

@doc raw"""
    is_pointed(S::AffineSemigroup)

Check whether the cone of the affine semigroup `S` is pointed.
"""
@attr Bool function is_pointed(S::AffineSemigroup)
  return is_pointed(polyhedral_cone(S))
end

@attr Cone{QQFieldElem} function polyhedral_cone(S::AffineSemigroup)
  G = [S.generators[i, :] for i in 1:nrows(S.generators)]
  return positive_hull(G)
end

@attr Polyhedron function cone(S::AffineSemigroup)
  return polyhedron(polyhedral_cone(S))
end

@attr Vector{HyperplaneQ} function hyperplanes(S::AffineSemigroup)
  return get_bounding_hyperplanes(cone(S))
end

@attr Tuple{Polyhedron,Vector{Int}} function zonotope(S::AffineSemigroup)
  return get_zonotope(cone(S))
end

